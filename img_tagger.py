def setup_logging(log_path: str | None) -> None:
    """
    Configures the logging system to write to a specified file.

    Args:
        log_path: The file path where logs should be written. If None, nothing
            is logged; warnings still reach the console through _warn().
    """

    if log_path is None:
        return

    path_obj = Path(log_path)
    # Create parent directory if it doesn't exist
    path_obj.parent.mkdir(parents=True, exist_ok=True)

    logging.basicConfig(
        filename=str(path_obj),
        # INFO for other libraries keeps httpx's request lines but drops Pillow's per-chunk DEBUG noise
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(threadName)s %(name)s: %(message)s",
        filemode="a",
        encoding="utf-8",
    )
    logger.setLevel(logging.DEBUG)
    logger.info(f"Logging started (Python {platform.python_version()} on {platform.system()})")


def _log_path_error(log_path: str | None) -> str | None:
    """
    Checks the --log path before anything is created or appended to it.

    The log holds raw model replies, which text inside an image can steer, so a
    misused --log (e.g. from a prompt-injected agent) must not append to shell
    profiles, keys or source files. Only regular .log files are accepted.

    Returns:
        The error message, or None if the path is acceptable (or logging is off).
    """

    if log_path is None:
        return None
    path = Path(log_path)
    if path.suffix.lower() != ".log":
        return f"The log file '{log_path}' must end in .log"
    if path.is_symlink():
        return f"The log file '{log_path}' must not be a symlink"
    if path.exists() and not path.is_file():
        return f"The log file '{log_path}' must be a regular file"
    return None


def _warn(message: str) -> None:
    """Logs a warning and shows it on the console too, so it is seen with or without --log."""

    logger.warning(message)
    tqdm.write(f"  Warning: {message}")


def listen_for_quit(stop_event: threading.Event) -> None:
    """
    A daemon thread that monitors standard input for a 'q' keypress to trigger
    a graceful shutdown across different operating systems without hogging the CPU.

    Args:
        stop_event: A threading.Event object that will be set when 'q' is pressed.
    """

    if platform.system() == "Windows" and msvcrt is not None:
        _wait_for_quit_windows(stop_event)
        return

    try:
        with _cbreak_stdin():
            _wait_for_quit_posix(stop_event)
    except Exception as e:  # noqa: BLE001 - any terminal setup failure falls back to plain reads
        logger.debug(f"Terminal input unavailable ({e}); basic fallback active")
        # The extra sleep prevents hot-spinning on endless non-tty input (e.g. `yes |`)
        _wait_for_quit_posix(stop_event, idle_sleep=0.1)


def _wait_for_quit_windows(stop_event: threading.Event) -> None:
    """Polls the Windows console for a 'q' keypress until stop_event is set."""

    if msvcrt is None:
        return
    while not stop_event.is_set():
        if msvcrt.kbhit() and msvcrt.getch().decode("utf-8", errors="ignore").lower() == "q":
            stop_event.set()
            return
        time.sleep(0.05)  # Prevents a 100% CPU hot-spin on Windows when idle


@contextlib.contextmanager
def _cbreak_stdin() -> Generator[None]:
    """
    Puts the stdin terminal into cbreak mode (keys arrive without Enter) and
    restores the previous settings on exit.

    Raises:
        ImportError: If termios/tty are unavailable.
        termios.error: If stdin is not a terminal.
    """

    if termios is None or tty is None:
        raise ImportError("termios/tty not available")

    fd = sys.stdin.fileno()
    old_settings = termios.tcgetattr(fd)
    try:
        tty.setcbreak(fd)
        yield
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old_settings)


def _wait_for_quit_posix(stop_event: threading.Event, idle_sleep: float = 0.0) -> None:
    """
    Reads stdin until 'q' is pressed (sets stop_event), stdin reaches EOF,
    or stop_event is set elsewhere.

    Reads the raw file descriptor rather than sys.stdin: sys.stdin.read(1) pulls every
    pending byte into Python's buffer, so select() would no longer see them and a 'q'
    arriving in the same burst as another key (paste, key repeat) would be missed.

    Args:
        stop_event: Event to set when 'q' is pressed.
        idle_sleep: Extra delay per loop iteration, on top of the select() timeout.
    """

    fd = sys.stdin.fileno()
    while not stop_event.is_set():
        # select waits up to 0.1 seconds for input
        if select.select([fd], [], [], 0.1)[0]:
            data = os.read(fd, 1024)
            if not data:  # EOF reached (detached terminal / closed stdin)
                logger.debug("Stdin EOF reached; exiting Q monitor thread.")
                return
            if b"q" in data.lower():
                stop_event.set()
                return
        time.sleep(idle_sleep)


class _UnsafeImagePath(OSError):
    """An image path cannot be used without crossing a filesystem trust boundary."""


def _check_directory(info: os.stat_result) -> None:
    """Reject directories another POSIX user can replace entries in."""
    if info.st_uid not in {0, os.geteuid()}:
        raise _UnsafeImagePath("Image directory must belong to this user or root")
    if info.st_mode & 0o022:
        raise _UnsafeImagePath("Image directories must not be writable by other users")


def _check_windows_path(path: Path) -> None:
    """Reject existing Windows symlinks, junctions and other reparse points."""
    for part in (*reversed(path.parents), path):
        info = part.lstat()
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise _UnsafeImagePath(f"Image paths must not contain links or reparse points: {part}")


@contextlib.contextmanager
def _image_parent(path: Path) -> Generator[tuple[Path, int | None]]:
    """Pin POSIX ancestors without following links; Windows checks existing reparse points."""
    if ".." in path.parts:
        raise _UnsafeImagePath("Image paths must not contain '..'")
    path = path.absolute()
    if os.name == "nt":
        _check_windows_path(path.parent)
        yield path, None
        return
    # O_PATH preserves access through execute-only ancestors without requiring directory listing rights.
    flags = getattr(os, "O_PATH", os.O_RDONLY) | os.O_DIRECTORY | os.O_NOFOLLOW
    with contextlib.ExitStack() as stack:
        fd = os.open(path.anchor, flags)
        stack.callback(os.close, fd)
        for part in path.parent.parts[1:]:
            fd = os.open(part, flags, dir_fd=fd)
            stack.callback(os.close, fd)
        _check_directory(os.fstat(fd))
        yield path, fd


def _file_attributes(fd: int) -> dict[str, bytes]:
    """Capture extended attributes, including POSIX ACLs, without reopening a pathname."""
    if not hasattr(os, "listxattr"):
        return {}
    try:
        return {name: os.getxattr(fd, name) for name in os.listxattr(fd)}
    except OSError as error:
        if error.errno not in {errno.ENOTSUP, errno.EOPNOTSUPP}:
            raise
        return {}


def _apply_permissions(output: BinaryIO, mode: int, attributes: dict[str, bytes]) -> None:
    """Preserve source ACLs and remove any inherited temporary-file access grants."""
    fd = output.fileno()
    existing = _file_attributes(fd)
    for name in existing.keys() - attributes.keys():
        os.removexattr(fd, name)
    for name, value in attributes.items():
        if existing.get(name) != value:
            os.setxattr(fd, name, value)
    os.chmod(fd, stat.S_IMODE(mode))


def _source_bytes(path: Path, parent_fd: int | None) -> tuple[bytes, os.stat_result, dict[str, bytes]]:
    """Read only an opened regular file, rejecting leaf links before consuming bytes."""
    flags = os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NONBLOCK", 0)
    if parent_fd is not None:
        flags |= os.O_NOFOLLOW
    else:
        _check_windows_path(path)
    fd = os.open(path.name if parent_fd is not None else path, flags, dir_fd=parent_fd)
    with os.fdopen(fd, "rb") as source:
        info = os.fstat(source.fileno())
        if not stat.S_ISREG(info.st_mode):
            raise _UnsafeImagePath("Image input must be a regular file")
        if parent_fd is None:
            _check_windows_path(path)
            if not os.path.samestat(info, path.stat(follow_symlinks=False)):
                raise _UnsafeImagePath("Image changed while opening it")
        return source.read(), info, _file_attributes(source.fileno())


def _read_image_bytes(path: Path | str) -> bytes:
    """Read a guarded source snapshot instead of delegating pathname reads to libraries."""
    with _image_parent(Path(path)) as (image, parent_fd):
        return _source_bytes(image, parent_fd)[0]


def _open_pillow(path: Path | str | bytes) -> Image.Image:
    """Open Pillow on a private byte snapshot, never an attacker-replaceable pathname."""
    data = path if isinstance(path, bytes) else _read_image_bytes(path)
    return Image.open(io.BytesIO(data))


def _check_replacement(path: Path, parent_fd: int | None, expected: os.stat_result) -> None:
    """Refuse replacing a directory entry that no longer names the opened file."""
    current = os.stat(path.name if parent_fd is not None else path, dir_fd=parent_fd, follow_symlinks=False)
    if not os.path.samestat(current, expected):
        raise _UnsafeImagePath(f"File changed during processing: {path.name}")


@contextlib.contextmanager
def _image_edit(image_path: Path | str) -> Generator[tuple[bytes, BinaryIO]]:
    """Keep source permissions, parent identity and temporary descriptor bound to an edit."""
    with _image_parent(Path(image_path)) as (path, parent_fd):
        data, original, attributes = _source_bytes(path, parent_fd)
        fd, temporary = _create_image_temp(path.parent, parent_fd)
        expected = os.fstat(fd)
        try:
            with os.fdopen(fd, "w+b") as output:
                yield data, output
                output.flush()
                _apply_permissions(output, original.st_mode, attributes)
                _check_replacement(temporary, parent_fd, expected)
                _check_replacement(path, parent_fd, original)
                if parent_fd is not None:
                    robust_replace(temporary, path, parent_fd=parent_fd)
            if parent_fd is None:
                # Windows cannot rename an open CRT file; the remaining close/rename race is documented.
                _check_windows_path(path)
                _check_replacement(temporary, None, expected)
                _check_replacement(path, None, original)
                robust_replace(temporary, path)
        finally:
            if parent_fd is None:
                temporary.unlink(missing_ok=True)
            else:
                with contextlib.suppress(FileNotFoundError):
                    os.unlink(temporary.name, dir_fd=parent_fd)


def _create_image_temp(directory: Path, parent_fd: int | None) -> tuple[int, Path]:
    """Create a same-directory temporary without resolving mutable POSIX ancestors again."""
    if parent_fd is None:
        fd, name = tempfile.mkstemp(dir=directory, suffix=".tmp")
        return fd, Path(name)
    for _ in range(10):
        name = f"tmp{secrets.token_hex(12)}.tmp"
        try:
            fd = os.open(name, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=parent_fd)
            return fd, directory / name
        except FileExistsError:
            continue
    raise FileExistsError("Could not create a unique image temporary")


def get_image_format(img_path: Path | bytes) -> str | None:
    """
    Attempts to identify the image format using Pillow.

    Args:
        img_path: The path to the image file.

    Returns:
        The PIL format string (e.g., 'JPEG', 'PNG') or None if the file is not a valid image.
    """

    try:
        data = img_path if isinstance(img_path, bytes) else _read_image_bytes(img_path)
        with _open_pillow(data) as img:
            img.verify()
        # Re-open because verify() closes/clears the file handle in some versions
        with _open_pillow(data) as img:
            return img.format
    except Exception:  # noqa: BLE001 - Pillow raises arbitrary errors on malformed files
        return None


def _is_gif(img_path: Path, fmt: str | None) -> bool:
    """
    Tells whether a file is a GIF by its content (fmt from get_image_format()),
    falling back to the extension when Pillow couldn't read it (fmt is None).
    """

    return fmt == "GIF" if fmt else img_path.suffix.lower() == ".gif"


def robust_replace(src: Path, dst: Path, *, parent_fd: int | None = None) -> None:
    """Atomically replace dst with src, retrying on transient OSErrors like lingering file locks on Windows)."""
    for _ in range(10):
        try:
            if parent_fd is None:
                src.replace(dst)
            else:
                os.replace(src.name, dst.name, src_dir_fd=parent_fd, dst_dir_fd=parent_fd)
            return
        except OSError:
            time.sleep(0.5)
    raise OSError(f"Failed to replace {src} with {dst} after retries.")


def _sanitize_with_pillow(src, dst, fmt=None) -> None:
    """
    Re-saves an image with Pillow to strip broken metadata headers, keeping every
    frame, per-frame duration and loop count of animated images (WebP, APNG).

    Args:
        src: A guarded image path or source byte snapshot.
        dst: The retained temporary file object to write the sanitized copy to.
        fmt: Pillow format name to save as; defaults to the source image's format.
    """

    with _open_pillow(src) as img:
        fmt = fmt or img.format
        if not getattr(img, "is_animated", False):
            img.save(dst, format=fmt, quality=95)
            return

        durations = []
        for frame in ImageSequence.Iterator(img):
            frame.load()  # WebP only fills in the frame's duration once it's decoded
            durations.append(frame.info.get("duration", 100))
        img.seek(0)
        img.save(
            dst,
            format=fmt,
            quality=95,
            save_all=True,
            duration=durations,
            loop=img.info.get("loop", 0),
        )


def _modify_with_pyexiv2(output: BinaryIO, edit: Callable[[Any], None]) -> None:
    """
    Applies edit() to a file's metadata with pyexiv2 and saves the result in place.

    pyexiv2 gets the file's bytes rather than its path: on Windows it can't open paths
    with non-ASCII characters, in the file name or in any folder above it.

    Args:
        output: The retained temporary file object.
        edit: Called with the open pyexiv2.ImageData to modify its metadata.
    """

    output.seek(0)
    with pyexiv2.ImageData(output.read()) as img:
        edit(img)
        data = img.get_bytes()
    output.seek(0)
    output.write(data)
    output.truncate()


def write_metadata(image_path: str, tags_list: list[str]) -> None:
    """
    Writes tags to image metadata (JPEG, WebP, PNG) using pyexiv2.

    This function uses a temporary file for safe writing and includes an
    auto-healing fallback that sanitizes corrupted EXIF data using Pillow
    before retrying the write operation.

    Args:
        image_path: The path to the target image file.
        tags_list: A list of strings representing the tags to embed.
    """

    marker = PROCESSED_MARKER
    tags_str = ", ".join(tags_list)

    def write_tags(img: Any) -> None:
        img.modify_exif({"Exif.Photo.UserComment": f"{tags_str} {marker}"})
        img.modify_xmp(
            {
                "Xmp.dc.subject": tags_list,
                "Xmp.dc.description": f"Tags: {tags_str} | {marker}",
            }
        )

    with _image_edit(image_path) as (source, output):
        output.write(source)
        with metadata_lock:
            try:
                # Primary attempt using pyexiv2 (separated into EXIF and XMP)
                _modify_with_pyexiv2(output, write_tags)

            except RuntimeError as e:
                # Auto-healing fallback for corrupted EXIF data (IFD buffer errors)
                if "IFD" in str(e).upper() or "corrupt" in str(e).lower():
                    _warn(
                        f"Corrupted metadata in {Path(image_path).name} ({e}); "
                        "re-saving it with Pillow before tagging (JPEG/WebP are re-encoded)"
                    )

                    # Re-save the guarded source snapshot into the retained output handle.
                    output.seek(0)
                    output.truncate()
                    _sanitize_with_pillow(source, output)

                    # Retry pyexiv2 on the newly cleaned temporary file
                    _modify_with_pyexiv2(output, write_tags)

                else:
                    raise  # Re-raise if it's a different pyexiv2 error


def _gif_loop_kwargs(img: Image.Image) -> dict[str, int]:
    """
    Returns the save() loop argument that keeps a GIF's loop count.

    A GIF without a loop count plays once; saving it with loop=0 would make it loop forever.

    Args:
        img: The open source GIF.

    Returns:
        {"loop": count} if the GIF has a loop count, otherwise {}.
    """

    return {"loop": img.info["loop"]} if "loop" in img.info else {}


def write_gif_tags(image_path: str, tags_list: list[str]) -> None:
    """
    Writes tags to GIF images using comments, keeping frames, durations and loop count.

    Args:
        image_path: The path to the GIF file.
        tags_list: A list of strings representing the tags to embed.
    """

    with _image_edit(image_path) as (source, output):
        _save_gif(source, output, f"{', '.join(tags_list)} {PROCESSED_MARKER}")


def _save_gif(source: bytes, output: BinaryIO, comment: str) -> None:
    """Re-encode a source snapshot, preserving animation timing and loop semantics."""
    with _open_pillow(source) as img:
        loop = _gif_loop_kwargs(img)
        durations = [frame.info.get("duration", 100) for frame in ImageSequence.Iterator(img)]
        img.seek(0)
        first = img.copy()

        def frames():
            # Pillow collects these frames internally; memory still grows with animation size.
            for index, frame in enumerate(ImageSequence.Iterator(img)):
                if index:
                    yield frame.copy()

        try:
            first.save(
                output, format="GIF", save_all=True, append_images=frames(), duration=durations, comment=comment, **loop
            )
        finally:
            first.close()


def tag_image(image_path: str, tags_list: list[str], fmt: str | None = None) -> None:
    """
    Embeds a list of tags into an image's metadata.

    This function identifies the file format and routes to the appropriate
    writer (pyexiv2 for standard images, or custom logic for GIFs).

    Args:
        image_path: The filesystem path to the image file.
        tags_list: A list of strings representing the tags to embed.
        fmt: The image format (e.g., 'JPEG'). If None, it will be determined from the file.
    """

    img_path = Path(image_path)
    if fmt is None:
        fmt = get_image_format(img_path)

    if fmt is None:
        raise RuntimeError(f"Could not determine format for {image_path}")

    try:
        if fmt.lower() in ["jpg", "jpeg", "webp", "png"]:
            write_metadata(image_path, tags_list)
        elif fmt.lower() == "gif":
            write_gif_tags(image_path, tags_list)
        else:
            raise ValueError(f"Unsupported file format: {fmt}")
    except Exception as e:
        raise RuntimeError(f"Tagging failed for {image_path}: {e}") from e


def _clear_all(img: Any) -> None:
    """Wipes EXIF, XMP and IPTC from an open pyexiv2 image."""

    img.clear_exif()
    img.clear_xmp()
    # On WebP, clear_xmp() alone leaves the XMP chunk in the saved file;
    # also emptying the raw packet removes it (harmless for JPEG/PNG).
    img.modify_raw_xmp("")
    img.clear_iptc()


def _clear_standard(source: bytes, output: BinaryIO, fmt: str | None = None) -> str:
    """Clear a snapshot through pyexiv2, or sanitize corrupt metadata with Pillow."""
    output.write(source)
    try:
        with metadata_lock:
            _modify_with_pyexiv2(output, _clear_all)
        return "Cleared metadata (pyexiv2)"
    except RuntimeError as error:
        if "IFD" not in str(error).upper() and "corrupt" not in str(error).lower():
            raise
        logger.warning(f"Corrupted metadata ({error}); sanitizing image snapshot before clearing")
        output.seek(0)
        output.truncate()
        _sanitize_with_pillow(source, output, fmt)
        return "Sanitized and cleared (Pillow)"


def _clear_gif(source: bytes, output: BinaryIO) -> str:
    """Clear a GIF comment using only the opened source snapshot and output handle."""
    _save_gif(source, output, "")
    return "Cleared GIF comment"


def clear_tags(image_path: Path | str) -> None:
    """
    Removes all metadata (EXIF, XMP, IPTC) from standard images and clears
    comments from GIFs to reset images for testing purposes.

    Failures are printed rather than raised so one bad file doesn't stop a batch.

    Args:
        image_path: The path to the image file.
    """

    p = Path(image_path)
    if p.suffix.lower() not in IMAGE_EXTENSIONS:
        return
    try:
        with _image_edit(p) as (source, output):
            fmt = get_image_format(source)
            if _is_gif(p, fmt):
                message = _clear_gif(source, output)
            else:
                message = _clear_standard(source, output, fmt)
        separator = ": " if fmt == "GIF" else " for: "
        logger.info(f"{message}{separator}{p.name}")
        print(f"  {message}{separator}{p.name}")
    except Exception as e:
        logger.exception(f"Failed to clear {p.name}")
        print(f"  Failed to clear {p.name}: {e}")


def get_tags_ollama(client: Any, model: str, img_path: Path, prompt: str) -> str:
    """
    Sends an image and prompt to an Ollama server for tag generation.

    Args:
        client: The Ollama client instance.
        model: The identifier for the model to use (e.g., 'qwen3-vl:8b').
        img_path: The path to the image file.
        prompt: The prompt instructions for generating tags.

    Returns:
        A string containing the generated tags from the model response.
    """

    logger.debug(f"Requesting tags from Ollama ({model}) for {img_path}")
    response = client.chat(
        model=model,
        messages=[{"role": "user", "content": prompt, "images": [_read_image_bytes(img_path)]}],
    )
    content = response.message.content if hasattr(response, "message") else response["message"]["content"]
    logger.debug(f"Raw Ollama response for {img_path}: {content}")
    return content


def get_tags_lm_studio(client: Any, model: str, img_path: Path, prompt: str) -> str:
    """
    Encodes the image to base64 and sends a request to an LM Studio server.

    Args:
        client: The OpenAI-compatible client instance (e.g., LM Studio).
        model: The model identifier to use.
        img_path: The path to the image file.
        prompt: The text prompt for generating tags.

    Returns:
        A string containing the generated tags from the response content.
    """

    logger.debug(f"Requesting tags from LM Studio ({model}) for {img_path}")
    source = _read_image_bytes(img_path)
    fmt = get_image_format(source)
    if fmt is None:
        logger.error(f"Pillow could not determine the format for {img_path}")
    mime_map = {
        "jpeg": DEFAULT_MIME_TYPE,
        "jpg": DEFAULT_MIME_TYPE,
        "png": "image/png",
        "webp": "image/webp",
        "gif": "image/gif",
    }
    mime_type = mime_map.get((fmt or "").lower(), DEFAULT_MIME_TYPE)

    base64_image = base64.b64encode(source).decode("utf-8")

    response = client.chat.completions.create(
        model=model,
        messages=[
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": prompt},
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:{mime_type};base64,{base64_image}"},
                    },
                ],
            }
        ],
    )
    content = response.choices[0].message.content
    logger.debug(f"Raw LM Studio response for {img_path}: {content}")
    return content


def parse_model_output(raw_output: str) -> list[str] | None:
    """Parse model output and extract tags robustly with normalization.

    Tries multiple patterns (JSON, bullet points, intro text, comma-separated)
    to handle various LLM output styles. Returns None if parsing fails or
    insufficient tags are extracted.

    Args:
        raw_output: The raw string output from the LLM.

    Returns:
        A list of normalized tags, or None if no valid tags could be extracted.
    """

    # Thinking models (e.g. qwen3, deepseek-r1) may emit <think>...</think> reasoning before the answer
    if "</think>" in raw_output:
        raw_output = raw_output.rsplit("</think>", 1)[1]

    # Pattern 1: JSON array ["tag1", "tag2"] - most reliable
    parsed = None

    # Fast path: whole output is JSON
    try:
        parsed = json.loads(raw_output)
    except (ValueError, RecursionError):
        parsed = None

    # Fallback: find first bracketed segment and parse that
    if not isinstance(parsed, list):
        start = raw_output.find("[")
        end = raw_output.rfind("]")
        if start != -1 and end != -1 and end > start:
            candidate = raw_output[start : end + 1]
            try:
                parsed = json.loads(candidate)
            except (ValueError, RecursionError):
                parsed = None

    if isinstance(parsed, list):
        json_tags = [str(x).strip().lower() for x in parsed if isinstance(x, (str, int, float))]
        normalized = normalize_tags(json_tags)
        if normalized:
            return normalized
    # Pattern 2: Bullet points at line start (minimum 6 items expected); hyphens inside tags are not bullets
    bullets = re.findall(r"^[ \t]*[-•★●][ \t]*(\S.*)", raw_output, re.MULTILINE)
    if len(bullets) >= 6:
        return normalize_tags([t.strip().strip('"').lower() for b in bullets for t in b.split(",")])

    # Pattern 3: Numbered lists like "1. tag" (minimum 6 items expected)
    numbered = re.findall(r"(?<!\d)\d+\.\s+(.+)", raw_output)
    if len(numbered) >= 6:
        return normalize_tags([t.strip().strip('"').lower() for n in numbered for t in n.split(",")])

    # Pattern 4: "Here are the tags:" style intro text extraction. Needs a colon later on the same line
    # ("tags for this image:") or a dash right after, so a list item like "text tags" doesn't count.
    text_after_intro = re.match(
        r".{0,40}?\b(?:tags|keywords)\b(?:[^:\n]{0,40}:|\s*-)\s*(.+)",
        raw_output,
        re.IGNORECASE | re.DOTALL,
    )
    if text_after_intro:
        return normalize_tags(parse_text_tags(text_after_intro.group(1)))

    # Fallback: comma- and/or newline-separated
    return normalize_tags([tag.strip().strip("\"'").lower() for tag in re.split(r"[,\n]", raw_output) if tag.strip()])


def parse_text_tags(text: str) -> list[str]:
    """Parse tags from text that follows intro patterns.

    Args:
        text: The raw text output from the model.

    Returns:
        A list of extracted and cleaned tag strings.
    """

    # Split by commas or newlines
    parts = re.split(r"[,\n]+", text)
    tags = []
    for part in parts:
        part = part.strip().strip("\"'").lower()
        # Skip common non-tag words (short real tags like '3d' or 'ui' are kept)
        if part and part not in ["and", "or", "the", "a", "an", "is", "are", "of"]:
            tags.append(part)
    return tags


def normalize_tags(tags: list[str], min_count: int = 6, max_count: int = 12) -> list[str] | None:
    """Normalize tags and enforce count constraints.

    Normalizes each tag (lowercase, strip whitespace), removes duplicates while
    preserving order, then enforces the 6-12 tag minimum from your prompt.
    Returns None if fewer than min_count valid tags remain.

    Args:
        tags: A list of raw tags extracted from the model output.
        min_count: The minimum number of tags required to be considered valid.
        max_count: The maximum number of tags to keep.

    Returns:
        A list of normalized tags, or None if the count is below min_count.
    """

    # Strip, lowercase, remove duplicates while preserving order
    seen = set()
    normalized = []
    for tag in tags:
        tag = tag.strip().lower()
        if tag and tag not in seen:
            seen.add(tag)
            normalized.append(tag)

    # Enforce max_count (12) by trimming excess
    if len(normalized) > max_count:
        return normalized[:max_count]

    # Return None if we don't meet minimum, let caller decide how to handle it
    return normalized if len(normalized) >= min_count else None


def _contains_marker(value: object) -> bool:
    """Returns True if a metadata value (str, bytes or other) contains the processed marker."""

    if isinstance(value, bytes):
        value = value.decode("utf-8", errors="ignore")
    return bool(value) and PROCESSED_MARKER in str(value)


def _pyexiv2_has_marker(p: Path) -> bool:
    """
    Checks every EXIF and XMP value for the processed marker.

    Raises:
        Exception: If pyexiv2 cannot open the file.
    """

    values = []
    # Hand pyexiv2 the bytes, not the path: on Windows it can't open non-ASCII paths like 'ö'
    data = _read_image_bytes(p)
    with metadata_lock, pyexiv2.ImageData(data) as img:
        # Read EXIF and XMP independently so one failing doesn't kill both
        for kind, read in (("EXIF", img.read_exif), ("XMP", img.read_xmp)):
            try:
                values.extend(read().values())
            except Exception as e:  # noqa: BLE001 - the other read may still find the marker
                _warn(f"Could not read the {kind} metadata of {p.name} ({e})")
    return any(_contains_marker(v) for v in values)


def _pillow_has_marker(p: Path) -> bool:
    """
    Checks Pillow's text metadata (e.g. PNG text chunks) for the processed marker.

    Raises:
        Exception: If Pillow cannot open the file.
    """

    with _open_pillow(p) as img:
        return any(isinstance(v, str) and PROCESSED_MARKER in v for v in img.info.values())


def is_already_processed(img_path: Path, fmt: str | None = None) -> bool:
    """Checks if the image already contains the AI processed marker.

    Like tag_image(), it goes by the real format, not the extension: a PNG named
    .gif is tagged via pyexiv2, so its marker is in EXIF/XMP, not a GIF comment.

    Args:
        img_path: The path to the image file to check.
        fmt: The format from get_image_format(); looked up if None.

    Returns:
        True if the marker is found in metadata or comments, False otherwise.
    """

    p = Path(img_path)
    if p.suffix.lower() not in IMAGE_EXTENSIONS:
        return False

    if _is_gif(p, fmt or get_image_format(p)):
        try:
            with _open_pillow(p) as img:
                return _contains_marker(img.info.get("comment"))
        except Exception as e:  # noqa: BLE001
            _warn(f"Could not read the GIF comment of {p.name} ({e}); treating it as not yet tagged")
        return False

    # 1. Primary metadata inspection using pyexiv2
    try:
        if _pyexiv2_has_marker(p):
            return True
    except Exception as e:  # noqa: BLE001 - unreadable metadata means "not processed"
        _warn(f"pyexiv2 could not read the metadata of {p.name} ({e}); checking it with Pillow instead")

    # 2. Fully isolated fallback check using Pillow
    try:
        return _pillow_has_marker(p)
    except Exception as e:  # noqa: BLE001
        _warn(f"Could not read the metadata of {p.name} ({e}); treating it as not yet tagged")
    return False


def process_single_image(
    img_path: Path,
    client: Any,
    backend: str,
    model: str,
    prompt: str,
    stop_event: threading.Event,
) -> tuple[str, str, str, float]:
    """Handles the full pipeline for a single image: validation -> AI -> tagging.

    Args:
        img_path: The path to the image file to process.
        client: The client instance for the chosen backend (Ollama or OpenAI).
        backend: The backend type ('ollama' or 'lm-studio').
        model: The model identifier to use.
        prompt: The prompt instructions for tag generation.
        stop_event: A threading.Event to monitor for user cancellation.

    Returns:
        A tuple containing (status, filename, message, duration).
    """

    logger.info(f"Processing {img_path.name}")
    fmt = get_image_format(img_path)
    if fmt is None:
        logger.warning(f"Skipping invalid/unsupported file: {img_path.name}")
        return "FAILED", img_path.name, "Skipping unsupported or corrupted file", 0
    if fmt not in TAGGABLE_FORMATS:
        # e.g. a BMP named .jpg or an MPO (multi-picture) JPEG: fail before asking the model
        logger.warning(f"Skipping {img_path.name}: unsupported format {fmt}")
        return "FAILED", img_path.name, f"Unsupported file format: {fmt}", 0

    # Skip check
    if is_already_processed(img_path, fmt):
        logger.info(f"Skipping already processed image: {img_path.name}")
        return "SKIPPED", img_path.name, "Skipped: Already Tagged", 0

    if stop_event.is_set():
        logger.info(f"Cancelled before start: {img_path.name}")
        return "CANCELLED", img_path.name, "Cancelled by user", 0

    start = time.time()  # Start timing the actual processing
    try:
        if backend == "ollama":
            raw_output = get_tags_ollama(client, model, img_path, prompt)
        else:
            raw_output = get_tags_lm_studio(client, model, img_path, prompt)

        # Parse model output robustly (handles JSON, bullets, intro text, or comma-separated)
        parsed_tags = parse_model_output(raw_output)

        if not parsed_tags:
            logger.warning(
                f"Failed to extract valid tags from model response for {img_path.name} after {time.time() - start:.1f}s"
            )
            return (
                "FAILED",
                img_path.name,
                "Invalid or insufficient tags returned from model",
                time.time() - start,
            )

        tag_image(str(img_path), parsed_tags, fmt=fmt)
        logger.info(f"Tagged {img_path.name} in {time.time() - start:.1f}s with {parsed_tags}")
        return (
            "SUCCESS",
            img_path.name,
            f"Generated Tags: {parsed_tags}",
            time.time() - start,
        )

    except Exception as e:
        logger.exception(f"Error processing {img_path.name} after {time.time() - start:.1f}s")
        return "FAILED", img_path.name, str(e), time.time() - start


@dataclass
class _RunStats:
    """Running totals for one process_directory() call."""

    success: int = 0
    skipped: int = 0
    failed: int = 0
    success_duration: float = 0.0
    failed_log: list[tuple[str, str]] = field(default_factory=list)

    def record(self, status: str, name: str, message: str, duration: float) -> None:
        """Prints one process_single_image() result and adds it to the totals."""

        if status == "SUCCESS":
            tqdm.write(f"  [✓] {name} -> {message}")
            self.success += 1
            self.success_duration += duration
        elif status == "SKIPPED":
            tqdm.write(f"  [-] {name} -> {message}")
            self.skipped += 1
        elif status == "CANCELLED":
            # Do nothing for cancelled tasks to keep the console clean
            pass
        else:  # FAILED
            tqdm.write(f"  [!] {name} -> {message}")
            self.failed += 1
            self.failed_log.append((name, message))


def _find_images(directory: str, recursive: bool) -> list[Path]:
    """Lists files in directory (optionally recursive) with a supported image extension."""

    base_path = Path(directory)
    with _image_parent(base_path / ".image-directory-check"):
        files = base_path.rglob("*") if recursive else base_path.iterdir()
        # Reads revalidate ancestors and the opened leaf; this filter only avoids existing links.
        return [f for f in files if not f.is_symlink() and f.is_file() and f.suffix.lower() in IMAGE_EXTENSIONS]


def _load_prompt() -> str:
    """
    Loads prompt.txt from the script directory, falling back to DEFAULT_PROMPT
    if it doesn't exist. Exits the program if it exists but cannot be read.
    """

    prompt_file = Path(__file__).parent / "prompt.txt"
    if not prompt_file.exists():
        logger.warning(f"prompt.txt not found at {prompt_file}; using default")
        print(f"Warning: Could not read prompt.txt from {prompt_file}. Falling back to default.")
        return DEFAULT_PROMPT

    try:
        prompt = prompt_file.read_text(encoding="utf-8").strip()
    except Exception as e:
        logger.exception("Failed to read prompt.txt")
        print(f"Error: Could not read prompt.txt from {prompt_file}: {e}")
        sys.exit(1)
    logger.info(f"Using prompt from {prompt_file}")
    return prompt


def _create_client(backend: str, host: str, timeout: float = DEFAULT_TIMEOUT) -> Any:
    """
    Builds the model client for the chosen backend.

    Args:
        backend: The backend type ('ollama' or 'lm-studio').
        host: The endpoint URL for the chosen backend.
        timeout: Seconds to wait for a model reply before the request fails.

    Returns:
        The client, or None (after printing an error) if its library is not installed.
    """

    if backend == "ollama":
        if OllamaClient is None:
            print("Error: 'ollama' library not found. Please install it using 'pip install ollama'.")
            return None
        return OllamaClient(host=host, timeout=timeout)

    if OpenAI is None:
        print("Error: 'openai' library not found. Please install it using 'pip install openai'.")
        return None
    # No retries: a timed-out request would be resent to a server still busy with it.
    return OpenAI(base_url=f"{host}/v1", api_key="lm-studio", timeout=timeout, max_retries=0)


def _run_tasks(
    image_files: list[Path],
    client: Any,
    backend: str,
    model: str,
    prompt: str,
    max_workers: int,
    stop_event: threading.Event,
) -> _RunStats:
    """Tags image_files concurrently with a progress bar and returns the totals."""

    stats = _RunStats()
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_image = {
            executor.submit(
                process_single_image,
                img_path,
                client,
                backend,
                model,
                prompt,
                stop_event,
            ): img_path
            for img_path in image_files
        }

        stopped_notified = False
        for future in tqdm(
            as_completed(future_to_image),
            total=len(image_files),
            desc="Processing images",
        ):
            if stop_event.is_set() and not stopped_notified:
                tqdm.write("  [!] Stop signal received (Q pressed). Finishing currently running tasks...")
                logger.info("Stop requested (Q); finishing in-flight images, cancelling queued ones")
                stopped_notified = True

            try:
                stats.record(*future.result())
            except Exception as e:  # one bad image must not abort the batch
                img_path = future_to_image[future]
                logger.exception(f"Unexpected error for {img_path}")
                tqdm.write(f"  [!] {img_path} -> Unexpected Error: {e}")
                stats.failed += 1

    return stats


def _print_report(stats: _RunStats, total_seconds: float) -> None:
    """Prints the end-of-run summary."""

    hours, remainder = divmod(total_seconds, 3600)
    minutes, seconds = divmod(remainder, 60)

    print("\n" + "=" * 50)
    print("                PROCESSING REPORT")
    print("=" * 50)
    print(f" Processed images: {stats.success}")
    print(f" Skipped images: {stats.skipped}")
    print(f" Failed images: {stats.failed}")
    print(f" Total time elapsed: {int(hours)}h {int(minutes)}m {seconds:.2f}s")

    if stats.success > 0:
        avg_latency = stats.success_duration / stats.success
        print(f" Average processing time: {avg_latency:.2f} seconds")

    if stats.failed_log:
        print("\n--- Failed files details ---")
        for filename, error_msg in stats.failed_log:
            print(f" * {filename} -> {error_msg}")

    print("=" * 50)


def clear_directory(
    directory: str,
    recursive: bool = False,
    max_workers: int = 1,
) -> None:
    """
    Clears metadata (EXIF, XMP, IPTC) and comments from all supported images in a directory.

    Args:
        directory: The root directory to scan for images.
        recursive: Whether to include subdirectories.
        max_workers: Number of concurrent worker threads (1 to 4).
    """

    base_path = Path(directory)
    if not base_path.is_dir():
        print(f"Error: The path '{directory}' is not a valid directory.")
        return

    image_files = _find_images(directory, recursive)
    if not image_files:
        print(f"No valid images found in '{directory}'.")
        return

    print(f"Resetting tags for {len(image_files)} images...")
    logger.info(
        f"Clearing tags from {len(image_files)} images in {directory} (recursive={recursive}, workers={max_workers})"
    )
    if max_workers > 1:
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            list(executor.map(clear_tags, image_files))
    else:
        for img_path in image_files:
            clear_tags(img_path)
    print("Done.")
    logger.info("Clearing finished")


def process_directory(
    directory: str,
    recursive: bool = False,
    backend: str = "ollama",
    host: str = "http://localhost:11434",
    model: str = "qwen3-vl:8b",
    max_workers: int = 1,
    clear: bool = False,
    timeout: float = DEFAULT_TIMEOUT,
) -> None:
    """
    Orchestrates the image tagging process (or clearing when clear=True) for a directory.

    This function handles prompt loading, backend initialization (Ollama or LM Studio),
    concurrent task distribution via ThreadPoolExecutor, and provides a real-time progress
    bar and final summary report. When clear=True, it delegates to clear_directory().

    Args:
        directory: The root directory to scan for images.
        recursive: Whether to include subdirectories in the search.
        backend: The model provider backend ('ollama' or 'lm-studio').
        host: The endpoint URL for the chosen backend.
        model: The specific model name/ID to use.
        max_workers: The maximum number of concurrent threads (limited to 4).
        clear: If True, clears metadata and comments instead of tagging.
        timeout: Seconds to wait for each model reply before that image fails.
    """

    if clear:
        clear_directory(directory, recursive, max_workers)
        return

    image_files = _find_images(directory, recursive)
    if not image_files:
        print(f"No valid images found in '{directory}'.")
        return

    print(f"Initialized backend: {backend} | Target: {host}")
    print(f"Found {len(image_files)} images to process. Starting...\n")
    logger.info(
        f"Tagging {len(image_files)} images in {directory} (recursive={recursive}) via {backend} at {host}: "
        f"model={model}, workers={max_workers}, timeout={timeout:g}s"
    )

    prompt = _load_prompt()
    logger.debug(f"Prompt: {prompt}")
    client = _create_client(backend, host, timeout)
    if client is None:
        return

    start_time = time.time()

    # Concurrency and quitting
    stop_event = threading.Event()
    quit_thread = threading.Thread(target=listen_for_quit, args=(stop_event,), daemon=True)
    quit_thread.start()

    try:
        print(f"Starting concurrent processing (max_workers={max_workers}).")
        print("Press 'q' at any time to stop and see the current report.\n")
        stats = _run_tasks(image_files, client, backend, model, prompt, max_workers, stop_event)
    except Exception as e:
        print(f"An unexpected error occurred during processing: {e}")
        raise
    finally:
        # Also stops the quit listener after a normal finish, so it restores the
        # terminal (POSIX) and the report isn't held up waiting for it.
        stop_event.set()
        quit_thread.join(timeout=2)

    total_seconds = time.time() - start_time
    _print_report(stats, total_seconds)
    logger.info(
        f"Finished in {total_seconds:.1f}s: {stats.success} tagged, {stats.skipped} skipped, {stats.failed} failed"
    )


