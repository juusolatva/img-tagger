def setup_logging(log_path: str | None) -> None:
    """
    Configures the logging system to write to a specified file.

    Args:
        log_path: The file path where logs should be written. If None, nothing
            is logged; warnings still reach the console through _warn().

    Raises:
        OSError: If the log can't be opened or isn't a regular file of this user (see _open_log()).
    """

    if log_path is None:
        return

    path_obj = Path(log_path)
    # Create parent directory if it doesn't exist
    path_obj.parent.mkdir(parents=True, exist_ok=True)

    handler = _LogHandler(_open_log(path_obj))
    handler.setFormatter(_LogFormatter("%(asctime)s [%(levelname)s] %(threadName)s %(name)s: %(message)s"))
    # Not basicConfig(): it silently ignores the handler (leaking the open log) when the root logger
    # already has one, e.g. pytest's or an embedding application's. Only an earlier log of ours is replaced.
    root = logging.getLogger()
    for old in [h for h in root.handlers if isinstance(h, _LogHandler)]:
        root.removeHandler(old)
        old.close()
    # INFO for other libraries keeps httpx's request lines but drops Pillow's per-chunk DEBUG noise. As a
    # filter on our handler, not the root level, which is only raised to INFO, never lowered from a more
    # verbose level an embedding application set for its own handlers.
    handler.addFilter(lambda record: record.levelno >= logging.INFO or record.name.startswith(logger.name))
    root.addHandler(handler)
    if root.getEffectiveLevel() > logging.INFO:
        root.setLevel(logging.INFO)
    logger.setLevel(logging.DEBUG)
    logger.info(f"Logging started (Python {platform.python_version()} on {platform.system()})")


class _LogHandler(logging.StreamHandler):
    """The --log handler; unlike a plain StreamHandler, closing it also closes the log file."""

    def close(self) -> None:
        self.acquire()
        try:
            if not self.stream.closed:
                self.flush()
                self.stream.close()
        finally:
            self.release()
            super().close()


def _open_log(path: Path) -> TextIO:
    """
    Opens the log for appending once, without following a link at the leaf, and keeps that stream:
    a check by name followed by a later open could be raced by swapping the file for a symlink.
    The opened file must be a regular file and, on POSIX, belong to this user (a file someone
    else planted, e.g. in /tmp, would receive the raw model replies).
    """

    if os.name == "nt":
        # A new log gets a private DACL instead of the folder's inherited one (which may let others read it)
        access = _Win.FILE_APPEND_DATA | _Win.READ_CONTROL
        fd = _win_open(path, access, _Win.SHARE_ALL, _Win.OPEN_ALWAYS, security=_windows_private_security())
    else:
        # O_NONBLOCK: opening a FIFO fails (ENXIO) instead of waiting for a reader
        flags = os.O_WRONLY | os.O_APPEND | os.O_CREAT | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK
        fd = os.open(path, flags, 0o600)  # private: the log holds raw model replies and file paths
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or getattr(info, "st_file_attributes", 0) & _Win.ATTRIBUTE_REPARSE_POINT:
            raise OSError(errno.EINVAL, "The log file must be a regular file", str(path))
        if not _owned_by_current_user(fd, info):
            raise OSError(errno.EPERM, "The log file must belong to the current user", str(path))
        if os.name != "nt":
            os.set_blocking(fd, True)
        # backslashreplace like logging's own FileHandler: non-UTF-8 POSIX file names arrive as lone surrogates
        return open(fd, "a", encoding="utf-8", errors="backslashreplace")
    except BaseException:
        os.close(fd)
        raise


def _owned_by_current_user(fd: int, info: os.stat_result) -> bool:
    """Whether the open file belongs to this user (POSIX uid; Windows owner SID, see _windows_owned_by_me())."""
    return _windows_owned_by_me(fd) if os.name == "nt" else info.st_uid == os.geteuid()


def _log_path_error(log_path: str | None) -> str | None:
    """
    Checks the --log path before anything is created or appended to it.

    The log holds raw model replies, which text inside an image can steer, so a
    misused --log (e.g. from a prompt-injected agent) must not append to shell
    profiles, keys or source files. Only regular .log files are accepted.

    Returns:
        The error message, or None if the path is acceptable (or logging is off).
    """

    if log_path is None:
        return None
    path = Path(log_path)
    if path.suffix.lower() != ".log":
        return f"The log file '{log_path}' must end in .log"
    if path.is_symlink():
        return f"The log file '{log_path}' must not be a symlink"
    if path.exists() and not path.is_file():
        return f"The log file '{log_path}' must be a regular file"
    return None


# Characters that could fake output on a terminal or records in the line-oriented log when they come
# from a file name or a server: C0/C1 controls (newline, carriage return, escape sequences) and
# bidirectional overrides, which can make text display in a different order than it is.
_CONTROL_CHARACTERS = re.compile("[\x00-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]")


def _shown(text: str) -> str:
    """text with control characters escaped (a newline becomes \\n); other Unicode is kept as it is."""
    return _CONTROL_CHARACTERS.sub(lambda match: match.group().encode("unicode_escape").decode("ascii"), text)


class _LogFormatter(logging.Formatter):
    """Escapes control characters in each log message so every record stays one line (tracebacks are appended as is)."""

    def formatMessage(self, record: logging.LogRecord) -> str:
        return _shown(super().formatMessage(record))


def _warn(message: str) -> None:
    """Logs a warning and shows it on the console too, so it is seen with or without --log."""

    logger.warning(message)
    tqdm.write(f"  Warning: {_shown(message)}")


def listen_for_quit(stop_event: threading.Event) -> None:
    """
    A daemon thread that monitors standard input for a 'q' keypress to trigger
    a graceful shutdown across different operating systems without hogging the CPU.

    Args:
        stop_event: A threading.Event object that will be set when 'q' is pressed.
    """

    if platform.system() == "Windows" and msvcrt is not None:
        _wait_for_quit_windows(stop_event)
        return

    try:
        with _cbreak_stdin():
            _wait_for_quit_posix(stop_event)
    except Exception as e:  # noqa: BLE001 - any terminal setup failure falls back to plain reads
        logger.debug(f"Terminal input unavailable ({e}); basic fallback active")
        try:
            # The extra sleep prevents hot-spinning on endless non-tty input (e.g. `yes |`)
            _wait_for_quit_posix(stop_event, idle_sleep=0.1)
        except (OSError, ValueError, AttributeError) as error:  # no stdin (None, closed, or no file descriptor)
            logger.debug(f"No usable stdin ({error!r}); 'q' to quit is unavailable")


def _wait_for_quit_windows(stop_event: threading.Event) -> None:
    """Polls the Windows console for a 'q' keypress until stop_event is set."""

    if msvcrt is None:
        return
    while not stop_event.is_set():
        if msvcrt.kbhit():
            key = msvcrt.getch()
            if key in {b"\x00", b"\xe0"}:
                # Extended keys arrive as a prefix plus a scan code: Page Down is b"\xe0" b"Q"
                msvcrt.getch()
            elif key.lower() == b"q":
                stop_event.set()
                return
        time.sleep(0.05)  # Prevents a 100% CPU hot-spin on Windows when idle


@contextlib.contextmanager
def _cbreak_stdin() -> Generator[None]:
    """
    Puts the stdin terminal into cbreak mode (keys arrive without Enter) and
    restores the previous settings on exit.

    Raises:
        ImportError: If termios/tty are unavailable.
        termios.error: If stdin is not a terminal.
    """

    if termios is None or tty is None:
        raise ImportError("termios/tty not available")

    fd = sys.stdin.fileno()
    old_settings = termios.tcgetattr(fd)
    try:
        tty.setcbreak(fd)
        yield
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old_settings)


def _wait_for_quit_posix(stop_event: threading.Event, idle_sleep: float = 0.0) -> None:
    """
    Reads stdin until 'q' is pressed (sets stop_event), stdin reaches EOF,
    or stop_event is set elsewhere.

    Reads the raw file descriptor rather than sys.stdin: sys.stdin.read(1) pulls every
    pending byte into Python's buffer, so select() would no longer see them and a 'q'
    arriving in the same burst as another key (paste, key repeat) would be missed.

    Args:
        stop_event: Event to set when 'q' is pressed.
        idle_sleep: Extra delay per loop iteration, on top of the select() timeout.
    """

    fd = sys.stdin.fileno()
    while not stop_event.is_set():
        # select waits up to 0.1 seconds for input
        if select.select([fd], [], [], 0.1)[0]:
            data = os.read(fd, 1024)
            if not data:  # EOF reached (detached terminal / closed stdin)
                logger.debug("Stdin EOF reached; exiting Q monitor thread.")
                return
            if b"q" in data.lower():
                stop_event.set()
                return
        time.sleep(idle_sleep)


class _UnsafeImagePath(OSError):
    """An image path cannot be used without crossing a filesystem trust boundary."""


def _check_directory(info: os.stat_result, folder: Path | None = None) -> None:
    """Reject directories another POSIX user can replace entries in."""
    where = f": {folder}" if folder else ""
    if info.st_uid not in {0, os.geteuid()}:
        raise _UnsafeImagePath(f"Image folder must belong to this user or root{where}")
    if info.st_mode & 0o022:
        # Also with umask 0002 (user-private groups): the check can't tell a private group from a shared one
        raise _UnsafeImagePath(f"Image folder must not be writable by its group or other users (chmod go-w){where}")


