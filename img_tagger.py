def _win_error(code: int, path: Path | str | None = None) -> OSError:
    """Build the OSError subclass Python uses for a Win32 error code (e.g. FileExistsError)."""
    return OSError(0, ctypes.FormatError(code), None if path is None else str(path), code)


def _win_open(
    path: Path, access: int, share: int, disposition: int, flags: int = 0, security: bytes | None = None
) -> int:
    """Open a Windows handle without following a final reparse point and wrap it in a CRT descriptor."""
    attributes = None
    if security is not None:
        buffer = ctypes.create_string_buffer(security, len(security))
        descriptor = ctypes.cast(buffer, ctypes.c_void_p)
        attributes = ctypes.byref(_SecurityAttributes(ctypes.sizeof(_SecurityAttributes), descriptor, False))
    flags |= _Win.FLAG_OPEN_REPARSE_POINT
    handle = _kernel32.CreateFileW(str(path), access, share, attributes, disposition, flags, None)
    if handle in {None, wintypes.HANDLE(-1).value}:
        raise _win_error(ctypes.get_last_error(), path)
    try:
        return msvcrt.open_osfhandle(handle, 0)
    except OSError:
        _kernel32.CloseHandle(handle)
        raise


def _pin_windows_directory(path: Path) -> int:
    """
    Hold a directory open without delete sharing, so nobody can rename it or swap in a junction
    while the handle is open. A data right (traverse, else list) matters: Windows ignores the
    share mode of handles that only read attributes. A folder granting neither (reached through
    the "bypass traverse checking" privilege) is only checked for reparse points, not pinned.
    """
    for access in (_Win.FILE_TRAVERSE, _Win.FILE_LIST_DIRECTORY, 0):
        try:
            fd = _win_open(
                path,
                access | _Win.FILE_READ_ATTRIBUTES,
                _Win.SHARE_READ_WRITE,
                _Win.OPEN_EXISTING,
                _Win.FLAG_BACKUP_SEMANTICS,
            )
            break
        except PermissionError:
            if not access:
                raise
    try:
        info = os.fstat(fd)
        if info.st_file_attributes & _Win.ATTRIBUTE_REPARSE_POINT or not stat.S_ISDIR(info.st_mode):
            raise _UnsafeImagePath(f"Image paths must not contain links or reparse points: {path}")
    except BaseException:
        os.close(fd)
        raise
    return fd


def _windows_security(fd: int) -> bytes:
    """Return a file's DACL (with its inheritance flags) as a self-relative security descriptor."""
    descriptor = ctypes.c_void_p()
    handle = msvcrt.get_osfhandle(fd)
    info = _Win.DACL_SECURITY_INFORMATION
    error = _advapi32.GetSecurityInfo(
        handle, _Win.SE_FILE_OBJECT, info, None, None, None, None, ctypes.byref(descriptor)
    )
    if error:
        raise _win_error(error)
    try:
        return ctypes.string_at(descriptor, _advapi32.GetSecurityDescriptorLength(descriptor))
    finally:
        _kernel32.LocalFree(descriptor)


def _windows_private_security() -> bytes:
    """A self-relative security descriptor whose protected DACL lets only the file's owner in."""
    descriptor, size = ctypes.c_void_p(), wintypes.ULONG()
    if not _advapi32.ConvertStringSecurityDescriptorToSecurityDescriptorW(
        _Win.PRIVATE_SDDL, 1, ctypes.byref(descriptor), ctypes.byref(size)
    ):
        raise _win_error(ctypes.get_last_error())
    try:
        return ctypes.string_at(descriptor, size.value)
    finally:
        _kernel32.LocalFree(descriptor)


def _windows_owned_by_me(fd: int) -> bool:
    """
    Whether the file's owner is this process's user, or the default owner its new files get
    (an elevated administrator's files may belong to the Administrators group).
    """
    owner, descriptor = ctypes.c_void_p(), ctypes.c_void_p()
    handle = msvcrt.get_osfhandle(fd)
    info = _Win.OWNER_SECURITY_INFORMATION
    error = _advapi32.GetSecurityInfo(
        handle, _Win.SE_FILE_OBJECT, info, ctypes.byref(owner), None, None, None, ctypes.byref(descriptor)
    )
    if error:
        raise _win_error(error)
    try:
        return _windows_token_has_sid(owner)
    finally:
        _kernel32.LocalFree(descriptor)


def _windows_token_has_sid(sid: Any) -> bool:
    """
    Whether sid is this process's user SID or its default owner SID (TokenUser, TokenOwner). Compared
    here, while each token information buffer (which the SID pointer points into) is still alive.
    """
    token = wintypes.HANDLE()
    if not _advapi32.OpenProcessToken(_kernel32.GetCurrentProcess(), _Win.TOKEN_QUERY, ctypes.byref(token)):
        raise _win_error(ctypes.get_last_error())
    try:
        for token_class in (_Win.TOKEN_USER, _Win.TOKEN_OWNER):
            size = wintypes.DWORD()
            _advapi32.GetTokenInformation(token, token_class, None, 0, ctypes.byref(size))
            buffer = ctypes.create_string_buffer(size.value)
            if not _advapi32.GetTokenInformation(token, token_class, buffer, size, ctypes.byref(size)):
                raise _win_error(ctypes.get_last_error())
            # TOKEN_USER and TOKEN_OWNER both start with the SID pointer
            if _advapi32.EqualSid(sid, ctypes.c_void_p.from_buffer(buffer)):
                return True
        return False
    finally:
        _kernel32.CloseHandle(token)


def _windows_persistent_acls(fd: int) -> bool:
    """Tell whether the file's volume stores ACLs (FILE_PERSISTENT_ACLS; false on FAT32/exFAT)."""
    flags = wintypes.DWORD()
    handle = msvcrt.get_osfhandle(fd)
    if not _kernel32.GetVolumeInformationByHandleW(handle, None, 0, None, None, ctypes.byref(flags), None, 0):
        raise _win_error(ctypes.get_last_error())
    return bool(flags.value & _Win.FILE_PERSISTENT_ACLS)


def _windows_dacl(security: bytes) -> tuple[bytes | None, bool]:
    """Return a security descriptor's DACL entries (None for no DACL) and whether inheritance is blocked."""
    buffer = ctypes.create_string_buffer(security, len(security))
    present, defaulted, dacl = wintypes.BOOL(), wintypes.BOOL(), ctypes.c_void_p()
    control, revision = wintypes.WORD(), wintypes.DWORD()
    found = _advapi32.GetSecurityDescriptorDacl(
        buffer, ctypes.byref(present), ctypes.byref(dacl), ctypes.byref(defaulted)
    )
    if not found or not _advapi32.GetSecurityDescriptorControl(buffer, ctypes.byref(control), ctypes.byref(revision)):
        raise _win_error(ctypes.get_last_error())
    entries = None
    if present.value and dacl.value:
        # ACL header: revision, padding, then the WORD AclSize covering the whole list
        entries = ctypes.string_at(dacl, ctypes.c_uint16.from_address(dacl.value + 2).value)
    return entries, bool(control.value & _Win.SE_DACL_PROTECTED)


def _create_windows_temp(path: Path, security: bytes | None) -> int:
    """
    Create a temporary nobody else can open (share mode 0) that already carries the source DACL,
    so no other account can get a handle to it under the folder's broader inherited permissions.

    CreateFileW copies the entries as given (inherited ones included) but drops the DACL's
    auto-inherited marker flag; anything else differing fails closed before bytes are written.
    """
    access = _Win.GENERIC_READ | _Win.GENERIC_WRITE | _Win.DELETE | _Win.READ_CONTROL
    fd = _win_open(path, access, 0, _Win.CREATE_NEW, security=security)
    if security is not None:
        try:
            if _windows_dacl(_windows_security(fd)) != _windows_dacl(security):
                raise _UnsafeImagePath("Could not give the temporary file the image's permissions")
        except BaseException:
            _discard_windows_temp(fd, path)
            os.close(fd)
            raise
    return fd


def _discard_windows_temp(fd: int, temporary: Path) -> None:
    """
    Delete an uncommitted temporary through its handle (on close), even if it was made read-only.
    Does nothing once the handle no longer sits at the temporary's name: after a completed rename
    (e.g. Ctrl+C arriving right after it) the handle is the committed image.
    """
    with contextlib.suppress(OSError):
        if not os.path.samestat(os.fstat(fd), os.stat(temporary, follow_symlinks=False)):
            return
        os.chmod(fd, stat.S_IREAD | stat.S_IWRITE)
        delete = wintypes.BOOLEAN(True)
        handle = msvcrt.get_osfhandle(fd)
        if not _kernel32.SetFileInformationByHandle(
            handle, _Win.FILE_DISPOSITION_INFO, ctypes.byref(delete), ctypes.sizeof(delete)
        ):
            raise _win_error(ctypes.get_last_error())


def _rename_windows_handle(fd: int, target: Path) -> None:
    """
    Rename the open temporary over target through its handle, so no other file can take the
    temporary's place before the rename. Replaces read-only targets where the filesystem allows
    (FileRenameInfoEx, NTFS on Windows 10 1809+); elsewhere falls back to a plain replace.
    """
    if not target.is_absolute():
        raise ValueError(f"Rename target must be absolute, not resolved against the working directory: {target}")
    # Sized in UTF-16 code units: characters outside the BMP (e.g. emoji) take two
    name = str(target).encode("utf-16-le")

    class _RenameInfo(ctypes.Structure):
        _fields_ = [
            ("flags", wintypes.DWORD),  # a BOOLEAN ReplaceIfExists for FileRenameInfo
            ("root", wintypes.HANDLE),
            ("length", wintypes.DWORD),
            ("name", ctypes.c_ubyte * (len(name) + 2)),  # WCHAR[] plus the terminating null
        ]

    handle = msvcrt.get_osfhandle(fd)
    error = 0
    for info_class, flags in ((_Win.FILE_RENAME_INFO_EX, _Win.RENAME_EX_FLAGS), (_Win.FILE_RENAME_INFO, 1)):
        # Copied as raw bytes: c_char arrays stop at the first NUL, and UTF-16 has one in every ASCII character
        info = _RenameInfo(flags, None, len(name), (ctypes.c_ubyte * (len(name) + 2)).from_buffer_copy(name + b"\0\0"))
        if _kernel32.SetFileInformationByHandle(handle, info_class, ctypes.byref(info), ctypes.sizeof(info)):
            return
        error = ctypes.get_last_error()
        if error not in _Win.RENAME_EX_UNSUPPORTED:
            break
    raise _win_error(error, target)


@contextlib.contextmanager
def _image_parent(path: Path) -> Generator[tuple[Path, int | None]]:
    """
    Pin every ancestor without following links: POSIX through descriptors used for relative
    operations, Windows through handles that block renaming them (parent_fd is None there).
    """
    if ".." in path.parts:
        raise _UnsafeImagePath("Image paths must not contain '..'")
    path = path.absolute()
    if os.name == "nt":
        with contextlib.ExitStack() as stack:
            for part in (*reversed(path.parent.parents), path.parent):
                stack.callback(os.close, _pin_windows_directory(part))
            yield path, None
        return
    # O_PATH preserves access through execute-only ancestors without requiring directory listing rights.
    flags = getattr(os, "O_PATH", os.O_RDONLY) | os.O_DIRECTORY | os.O_NOFOLLOW
    with contextlib.ExitStack() as stack:
        fd = os.open(path.anchor, flags)
        stack.callback(os.close, fd)
        folder = Path(path.anchor)
        for part in path.parent.parts[1:]:
            folder /= part
            fd = _open_folder(folder, flags, fd)
            stack.callback(os.close, fd)
        _check_directory(os.fstat(fd), path.parent)
        yield path, fd


def _open_folder(folder: Path, flags: int, parent_fd: int) -> int:
    """Open one path part relative to its pinned parent, naming it if it is a symlink or not a folder."""
    try:
        return os.open(folder.name, flags, dir_fd=parent_fd)
    except OSError as error:
        # O_NOFOLLOW: a symlink gives ELOOP, or ENOTDIR together with O_PATH (Linux)
        if error.errno in {errno.ELOOP, errno.ENOTDIR}:
            raise _UnsafeImagePath(
                f"Image paths must not contain links: {folder} is a symlink or not a folder"
            ) from error
        raise


def _file_attributes(fd: int) -> dict[str, bytes]:
    """
    Capture the POSIX ACL and the user.* and SELinux extended attributes (see _kept_xattr()), or the
    Windows DACL, without reopening a pathname. Volumes that don't store ACLs (FAT32/exFAT) have no DACL to keep.
    """
    if os.name == "nt":
        return {_Win.SECURITY_KEY: _windows_security(fd)} if _windows_persistent_acls(fd) else {}
    if not hasattr(os, "listxattr"):
        return {}
    try:
        names = os.listxattr(fd)
    except OSError as error:
        if error.errno not in {errno.ENOTSUP, errno.EOPNOTSUPP}:
            raise
        return {}
    attributes = {}
    for name in filter(_kept_xattr, names):
        try:
            attributes[name] = os.getxattr(fd, name)
        except OSError as error:
            # The ACL decides who may read the image: fail closed unless it has just been removed (ENODATA).
            # Other attributes are best effort, e.g. one removed meanwhile or one this user may not read.
            if name == ACL_XATTR and error.errno != errno.ENODATA:
                raise
            logger.debug(f"Could not read extended attribute {name}: {error}")
    return attributes


def _kept_xattr(name: str) -> bool:
    """
    The extended attributes an edit carries over: the access ACL (permissions), user.* (user data)
    and the SELinux label (best effort). Other security.* and trusted.* attributes are kernel-
    or root-managed (e.g. security.capability, security.ima); an unprivileged user can't write them.
    """
    return name in {ACL_XATTR, SELINUX_XATTR} or name.startswith("user.")


def _restore_xattrs(fd: int, attributes: dict[str, bytes]) -> None:
    """
    Give the temporary exactly the source's kept attributes: inherited ACL entries (a default ACL on
    the folder) are removed, the source ACL is set and any failure there propagates (fail closed).
    The SELinux label is only attempted: a new file gets its folder's default label, and changing it
    needs a policy permission the user may lack (e.g. for an image moved in from ~/Downloads or /tmp).
    """
    existing = _file_attributes(fd)
    for name in existing.keys() - attributes.keys() - {SELINUX_XATTR}:
        os.removexattr(fd, name)
    for name, value in attributes.items():
        if existing.get(name) == value:
            continue
        if name != SELINUX_XATTR:
            os.setxattr(fd, name, value)
            continue
        try:
            os.setxattr(fd, name, value)
        except OSError as error:
            logger.debug(f"Kept the folder's default SELinux label instead of the source's: {error}")


def _restore_group(fd: int, source: os.stat_result, name: str, acl: bytes | None = None) -> int:
    """
    Give the POSIX temporary the source's owning group, so the kept mode doesn't grant its group
    bits to a different (e.g. setgid-directory or primary) group. If that group can't be set
    (this user isn't a member, or the filesystem/user namespace refuses it, e.g. EINVAL for an
    unmapped gid), group access is dropped instead, and the other bits are limited to what the
    owning group had (_owning_group_bits(), from the source ACL if any): members of the source
    group now count as others, so with 0604 they would gain the read access that mode denied them.
    Returns the mode to apply.
    """
    mode = stat.S_IMODE(source.st_mode)
    if os.fstat(fd).st_gid == source.st_gid:
        return mode
    try:
        os.fchown(fd, -1, source.st_gid)
        return mode
    except OSError as error:
        _warn(f"Could not keep group {source.st_gid} on {name} ({error}); removed its group permissions instead")
        return (mode & ~0o077) | (mode & 0o007 & _owning_group_bits(mode, acl))


def _owning_group_bits(mode: int, acl: bytes | None) -> int:
    """
    The owning group's rwx bits. With a POSIX ACL the mode's group bits are the ACL mask, which may
    allow more than the group entry (group::--- with mask::rw-), so read the ACL_GROUP_OBJ entry of
    the system.posix_acl_access value (u32 version, then u16 tag, u16 perm, u32 id per entry).
    An ACL without one counts as no access.
    """
    if not acl:
        return (mode >> 3) & 0o7
    for offset in range(4, len(acl) - 7, 8):
        tag, perm, _ = struct.unpack_from("<HHI", acl, offset)
        if tag == 0x04:  # ACL_GROUP_OBJ
            return perm & 0o7
    return 0


def _apply_permissions(output: BinaryIO, source: os.stat_result, attributes: dict[str, bytes], image_name: str) -> None:
    """
    Preserve the source group and ACLs and remove any inherited temporary-file access grants, then
    the mode (on Windows only the read-only attribute; the DACL was set when the temporary was created).
    """
    fd = output.fileno()
    mode = stat.S_IMODE(source.st_mode)
    if os.name != "nt":
        mode = _restore_group(fd, source, image_name, attributes.get(ACL_XATTR))
        _restore_xattrs(fd, attributes)
    os.chmod(fd, mode)


def _source_bytes(
    path: Path, parent_fd: int | None, permissions: bool = False, found: os.stat_result | None = None
) -> tuple[bytes, os.stat_result, dict[str, bytes]]:
    """
    Read only an opened regular file, rejecting leaf links before consuming bytes. With permissions,
    also capture its extended attributes/ACLs or DACL (only edits need them). With found (its
    lstat from _find_images()), refuse a different file now at that path: someone allowed to
    rename folders above it could otherwise swap in another collection between discovery and here.
    """
    if parent_fd is None:
        fd = _win_open(path, _Win.GENERIC_READ, _Win.SHARE_ALL, _Win.OPEN_EXISTING)
    else:
        flags = os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_NONBLOCK", 0)
        fd = os.open(path.name, flags, dir_fd=parent_fd)
    with os.fdopen(fd, "rb") as source:
        info = os.fstat(source.fileno())
        if not stat.S_ISREG(info.st_mode) or getattr(info, "st_file_attributes", 0) & _Win.ATTRIBUTE_REPARSE_POINT:
            raise _UnsafeImagePath("Image input must be a regular file")
        if found is not None and not os.path.samestat(info, found):
            raise _UnsafeImagePath(f"File changed since it was found: {path.name}")
        if parent_fd is not None:
            os.set_blocking(source.fileno(), True)  # O_NONBLOCK was only for refusing FIFOs at open
        # Checked before and while reading, so a file that grows meanwhile is bounded too
        if info.st_size > MAX_IMAGE_BYTES or len(data := source.read(MAX_IMAGE_BYTES + 1)) > MAX_IMAGE_BYTES:
            raise OSError(errno.EFBIG, f"Image is larger than {MAX_IMAGE_BYTES // 2**20} MiB", path.name)
        return data, info, _file_attributes(source.fileno()) if permissions else {}


def _read_image_snapshot(path: Path | str, found: os.stat_result | None = None) -> tuple[bytes, os.stat_result]:
    """
    Read a guarded source snapshot instead of delegating pathname reads to libraries, with the
    stat of the file it came from (see _same_version()); found as in _source_bytes().
    """
    with _image_parent(Path(path)) as (image, parent_fd):
        data, info, _ = _source_bytes(image, parent_fd, found=found)
        return data, info


def _read_image_bytes(path: Path | str) -> bytes:
    """The bytes of _read_image_snapshot()."""
    return _read_image_snapshot(path)[0]


def _same_version(current: os.stat_result, expected: os.stat_result) -> bool:
    """Whether current is the same, unmodified file as expected (same file identity, size and mtime)."""
    return (
        os.path.samestat(current, expected)
        and current.st_size == expected.st_size
        and current.st_mtime_ns == expected.st_mtime_ns
    )


def _open_pillow(path: Path | str | bytes) -> Image.Image:
    """Open Pillow on a private byte snapshot, never an attacker-replaceable pathname."""
    data = path if isinstance(path, bytes) else _read_image_bytes(path)
    return Image.open(io.BytesIO(data))


def _check_replacement(
    path: Path,
    parent_fd: int | None,
    expected: os.stat_result,
    same: Callable[[os.stat_result, os.stat_result], bool] = os.path.samestat,
) -> None:
    """Refuse replacing a directory entry that no longer names the opened file (by same(), default identity)."""
    current = os.stat(path.name if parent_fd is not None else path, dir_fd=parent_fd, follow_symlinks=False)
    if not same(current, expected):
        raise _UnsafeImagePath(f"File changed during processing: {path.name}")


@contextlib.contextmanager
def _image_edit(
    image_path: Path | str, expected: os.stat_result | None = None, found: os.stat_result | None = None
) -> Generator[tuple[bytes, BinaryIO]]:
    """
    Keep source permissions, parent identity and temporary descriptor bound to an edit. With expected
    (the stat of an earlier snapshot, e.g. the one sent to the model), refuse a file that has since
    been replaced or modified; found as in _source_bytes().
    """
    with _image_parent(Path(image_path)) as (path, parent_fd):
        data, original, attributes = _source_bytes(path, parent_fd, permissions=True, found=found)
        if expected is not None and not _same_version(original, expected):
            raise _UnsafeImagePath(f"File changed during processing: {path.name}")
        fd, temporary = _create_image_temp(path.parent, parent_fd, attributes.get(_Win.SECURITY_KEY))
        try:
            with _temp_file_object(fd, temporary, parent_fd) as output:
                try:
                    temp_stat = os.fstat(output.fileno())
                    # Before the first byte is written: EFS protects only the file itself, not its replacement
                    if _efs_encrypted(original) and not _efs_encrypted(temp_stat):
                        raise _UnsafeImagePath(
                            f"Encrypted (EFS) image would be replaced by an unencrypted file: {path.name}"
                        )
                    yield data, output
                    output.flush()
                    _apply_permissions(output, original, attributes, path.name)
                    _check_replacement(temporary, parent_fd, temp_stat)
                    # Unchanged, not just the same file: an edit by another program meanwhile must not be overwritten
                    _check_replacement(path, parent_fd, original, _same_version)
                    # Windows renames the still-open temporary through its handle
                    source_fd = output.fileno() if parent_fd is None else None
                    robust_replace(temporary, path, parent_fd=parent_fd, source_fd=source_fd)
                except BaseException:
                    if parent_fd is None:
                        _discard_windows_temp(output.fileno(), temporary)
                    raise
        finally:
            if parent_fd is not None:
                with contextlib.suppress(FileNotFoundError):
                    os.unlink(temporary.name, dir_fd=parent_fd)


def _temp_file_object(fd: int, temporary: Path, parent_fd: int | None) -> BinaryIO:
    """The temporary's descriptor as a file object; if even that fails, the descriptor is still closed."""
    try:
        return os.fdopen(fd, "w+b")
    except BaseException:
        if parent_fd is None:
            _discard_windows_temp(fd, temporary)
        os.close(fd)
        raise


def _efs_encrypted(info: os.stat_result) -> bool:
    """
    Whether Windows EFS encrypts the file (FILE_ATTRIBUTE_ENCRYPTED). A temporary created in an
    encrypted folder is encrypted at creation; one in a plain folder is not, and replacing an
    individually encrypted image with it would leave the image readable without the EFS key.
    """
    return bool(getattr(info, "st_file_attributes", 0) & _Win.ATTRIBUTE_ENCRYPTED)


def _create_image_temp(directory: Path, parent_fd: int | None, security: bytes | None = None) -> tuple[int, Path]:
    """
    Create a same-directory temporary without resolving mutable POSIX ancestors again; on Windows
    (parent_fd None) it gets the source's DACL (security) and no sharing.
    """
    for _ in range(10):
        name = f"tmp{secrets.token_hex(12)}.tmp"
        try:
            if parent_fd is None:
                return _create_windows_temp(directory / name, security), directory / name
            fd = os.open(name, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=parent_fd)
            return fd, directory / name
        except FileExistsError:
            continue
    raise FileExistsError("Could not create a unique image temporary")


def get_image_format(img_path: Path | bytes) -> str | None:
    """
    Attempts to identify the image format using Pillow.

    Args:
        img_path: The path to the image file.

    Returns:
        The PIL format string (e.g., 'JPEG', 'PNG') or None if the file is not a valid image.
    """

    try:
        data = img_path if isinstance(img_path, bytes) else _read_image_bytes(img_path)
        with _open_pillow(data) as img:
            img.verify()
        # Re-open because verify() closes/clears the file handle in some versions
        with _open_pillow(data) as img:
            return img.format
    except Exception as error:  # noqa: BLE001 - Pillow raises arbitrary errors on malformed files
        label = "image data" if isinstance(img_path, bytes) else Path(img_path).name
        logger.debug(f"Could not identify {label} as an image: {error!r}")
        return None


def _is_gif(img_path: Path, fmt: str | None) -> bool:
    """
    Tells whether a file is a GIF by its content (fmt from get_image_format()),
    falling back to the extension when Pillow couldn't read it (fmt is None).
    """

    return fmt == "GIF" if fmt else img_path.suffix.lower() == ".gif"


def robust_replace(src: Path, dst: Path, *, parent_fd: int | None = None, source_fd: int | None = None) -> None:
    """
    Atomically replace dst with src, retrying on transient OSErrors like lingering file locks on Windows.
    With parent_fd both names are relative to that POSIX directory; with source_fd (Windows) src is
    renamed through that open descriptor.
    """
    last_error: OSError | None = None
    for attempt in range(10):
        if attempt:
            time.sleep(0.5)
        try:
            if source_fd is not None:
                _rename_windows_handle(source_fd, dst)
            elif parent_fd is None:
                src.replace(dst)
            else:
                os.replace(src.name, dst.name, src_dir_fd=parent_fd, dst_dir_fd=parent_fd)
            return
        except OSError as error:
            last_error = error
    raise OSError(f"Failed to replace {dst} with {src} after retries: {last_error}") from last_error


def _sanitize_with_pillow(src, dst, fmt=None) -> None:
    """
    Re-saves an image with Pillow to strip broken metadata headers, keeping every
    frame, per-frame duration and loop count of animated images (WebP, APNG).

    Args:
        src: A guarded image path or source byte snapshot.
        dst: The retained temporary file object to write the sanitized copy to.
        fmt: Pillow format name to save as; defaults to the source image's format.
    """

    with _open_pillow(src) as img:
        fmt = fmt or img.format
        if not getattr(img, "is_animated", False):
            img.save(dst, format=fmt, quality=95)
            return
        # Every frame is decoded and Pillow's writers keep them all: bound the total before decoding any
        if img.n_frames * img.width * img.height > MAX_ANIMATION_PIXELS:
            raise ValueError(
                f"Animation too large to repair ({img.n_frames} frames of {img.width}x{img.height} pixels)"
            )

        durations = []
        for frame in ImageSequence.Iterator(img):
            frame.load()  # WebP only fills in the frame's duration once it's decoded
            durations.append(frame.info.get("duration", 100))
        img.seek(0)
        img.save(
            dst,
            format=fmt,
            quality=95,
            save_all=True,
            duration=durations,
            loop=img.info.get("loop", 0),
        )


def _is_corrupt_metadata_error(error: RuntimeError) -> bool:
    """Tells whether a pyexiv2 error means broken metadata that a Pillow re-save can repair."""

    return "IFD" in str(error).upper() or "corrupt" in str(error).lower()


def _modify_with_pyexiv2(output: BinaryIO, edit: Callable[[Any], None]) -> None:
    """
    Applies edit() to a file's metadata with pyexiv2 and saves the result in place.

    pyexiv2 gets the file's bytes rather than its path: on Windows it can't open paths
    with non-ASCII characters, in the file name or in any folder above it.

    Args:
        output: The retained temporary file object.
        edit: Called with the open pyexiv2.ImageData to modify its metadata.
    """

    output.seek(0)
    with pyexiv2.ImageData(output.read()) as img:
        edit(img)
        data = img.get_bytes()
    output.seek(0)
    output.write(data)
    output.truncate()


def write_metadata(image_path: str, tags_list: list[str], expected: os.stat_result | None = None) -> None:
    """
    Writes tags to image metadata (JPEG, WebP, PNG) using pyexiv2.

    This function uses a temporary file for safe writing and includes an
    auto-healing fallback that sanitizes corrupted EXIF data using Pillow
    before retrying the write operation.

    Args:
        image_path: The path to the target image file.
        tags_list: A list of strings representing the tags to embed.
        expected: The stat of the snapshot the tags describe; a file changed since then is refused.
    """

    marker = PROCESSED_MARKER
    tags_str = ", ".join(tags_list)

    def write_tags(img: Any) -> None:
        img.modify_exif({"Exif.Photo.UserComment": f"{tags_str} {marker}"})
        img.modify_xmp(
            {
                "Xmp.dc.subject": tags_list,
                "Xmp.dc.description": f"Tags: {tags_str} | {marker}",
            }
        )

    with _image_edit(image_path, expected) as (source, output):
        output.write(source)
        try:
            # Primary attempt using pyexiv2 (separated into EXIF and XMP)
            with metadata_lock:
                _modify_with_pyexiv2(output, write_tags)
            return
        except RuntimeError as e:
            # Auto-healing fallback for corrupted EXIF data (IFD buffer errors); other pyexiv2 errors propagate
            if not _is_corrupt_metadata_error(e):
                raise
            _warn(
                f"Corrupted metadata in {Path(image_path).name} ({e}); "
                "re-saving it with Pillow before tagging (JPEG/WebP are re-encoded)"
            )
        # Re-save the guarded source snapshot into the retained output handle. Pillow runs outside the
        # lock (like _clear_standard()), so other workers' pyexiv2 calls aren't held up by the re-encode.
        output.seek(0)
        output.truncate()
        _sanitize_with_pillow(source, output)
        # Retry pyexiv2 on the newly cleaned temporary file
        with metadata_lock:
            _modify_with_pyexiv2(output, write_tags)


def write_gif_tags(image_path: str, tags_list: list[str], expected: os.stat_result | None = None) -> None:
    """
    Writes tags to a GIF as its comment, leaving everything else in the file byte for byte unchanged.

    Args:
        image_path: The path to the GIF file.
        tags_list: A list of strings representing the tags to embed.
        expected: The stat of the snapshot the tags describe; a file changed since then is refused.
    """

    with _image_edit(image_path, expected) as (source, output):
        output.write(_set_gif_comment(source, f"{', '.join(tags_list)} {PROCESSED_MARKER}"))


def _set_gif_comment(source: bytes, comment: str) -> bytes:
    """
    The GIF with every comment extension removed and, unless comment is empty, one new comment
    (UTF-8) right after the global header, where Pillow reads it as info["comment"]. The GIF is
    edited at the block level, never decoded: frames, palettes, disposal methods, transparency,
    durations, the loop count and other extensions stay byte for byte, in memory of the file's size.

    Raises:
        ValueError: The data isn't a GIF or ends inside a block.
    """

    if source[:6] not in {b"GIF87a", b"GIF89a"}:
        raise ValueError("Not a GIF file")
    header_end = 13 + _gif_color_table_size(source, 10)
    _gif_byte(source, header_end - 1)  # the whole header and global color table must be there
    output = bytearray(source[:header_end])
    if comment:
        output[:6] = b"GIF89a"  # comment extensions are a GIF89a feature
        data = comment.encode("utf-8")
        output += b"\x21\xfe"
        for offset in range(0, len(data), 255):
            chunk = data[offset : offset + 255]
            output += bytes([len(chunk)]) + chunk
        output += b"\x00"
    position = header_end
    while position < len(source):
        block = source[position]
        if block == 0x21:  # extension: label, then data sub-blocks
            end = _gif_sub_blocks_end(source, position + 2)
            if _gif_byte(source, position + 1) != 0xFE:
                output += source[position:end]
        elif block == 0x2C:  # image: descriptor, local color table, LZW code size, data sub-blocks
            end = _gif_sub_blocks_end(source, position + 11 + _gif_color_table_size(source, position + 9))
            output += source[position:end]
        else:  # the trailer (0x3B), or data after the last image that readers ignore: keep it as it is
            return bytes(output + source[position:])
        position = end
    return bytes(output + b"\x3b")  # a GIF that ended without its trailer gets one


def _gif_color_table_size(data: bytes, packed_at: int) -> int:
    """Size of the color table that the packed-fields byte at packed_at announces (0 without one)."""
    packed = _gif_byte(data, packed_at)
    return 3 << ((packed & 0x07) + 1) if packed & 0x80 else 0


def _gif_sub_blocks_end(data: bytes, position: int) -> int:
    """The offset just after the chain of data sub-blocks starting at position (ended by a 0 size)."""
    while size := _gif_byte(data, position):
        position += 1 + size
    return position + 1


def _gif_byte(data: bytes, position: int) -> int:
    if position >= len(data):
        raise ValueError("Truncated GIF file")
    return data[position]


def tag_image(
    image_path: str, tags_list: list[str], fmt: str | None = None, expected: os.stat_result | None = None
) -> None:
    """
    Embeds a list of tags into an image's metadata.

    This function identifies the file format and routes to the appropriate
    writer (pyexiv2 for standard images, or custom logic for GIFs).

    Args:
        image_path: The filesystem path to the image file.
        tags_list: A list of strings representing the tags to embed.
        fmt: The image format (e.g., 'JPEG'). If None, it will be determined from the file.
        expected: The stat of the snapshot the tags describe (_read_image_snapshot()); if the file
            was replaced or modified since then, tagging fails instead of mislabeling the new content.
    """

    img_path = Path(image_path)
    if fmt is None:
        fmt = get_image_format(img_path)

    if fmt is None:
        raise RuntimeError(f"Could not determine format for {image_path}")

    try:
        if fmt in PYEXIV2_FORMATS:
            write_metadata(image_path, tags_list, expected)
        elif fmt == "GIF":
            write_gif_tags(image_path, tags_list, expected)
        else:
            raise ValueError(f"Unsupported file format: {fmt}")
    except Exception as e:
        raise RuntimeError(f"Tagging failed for {image_path}: {e}") from e


def _clear_all(img: Any) -> None:
    """Wipes EXIF, XMP and IPTC from an open pyexiv2 image."""

    img.clear_exif()
    img.clear_xmp()
    # On WebP, clear_xmp() alone leaves the XMP chunk in the saved file;
    # also emptying the raw packet removes it (harmless for JPEG/PNG).
    img.modify_raw_xmp("")
    img.clear_iptc()


def _clear_standard(source: bytes, output: BinaryIO, fmt: str | None = None) -> str:
    """Clear a snapshot through pyexiv2, or sanitize corrupt metadata with Pillow."""
    output.write(source)
    try:
        with metadata_lock:
            _modify_with_pyexiv2(output, _clear_all)
        return "Cleared metadata (pyexiv2)"
    except RuntimeError as error:
        if not _is_corrupt_metadata_error(error):
            raise
        logger.warning(f"Corrupted metadata ({error}); repairing image snapshot before clearing")
        output.seek(0)
        output.truncate()
        _sanitize_with_pillow(source, output, fmt)
        return "Repaired and cleared (Pillow)"


def _clear_gif(source: bytes, output: BinaryIO) -> str:
    """Remove a GIF's comments, leaving everything else byte for byte (see _set_gif_comment())."""
    output.write(_set_gif_comment(source, ""))
    return "Cleared GIF comment"


def clear_tags(image_path: Path | str, found: os.stat_result | None = None) -> None:
    """
    Removes all metadata (EXIF, XMP, IPTC) from standard images and clears
    comments from GIFs to reset images for testing purposes.

    Failures are printed rather than raised so one bad file doesn't stop a batch.

    Args:
        image_path: The path to the image file.
        found: The file's lstat from _find_images(); a different file at the path is refused.
    """

    p = Path(image_path)
    if p.suffix.lower() not in IMAGE_EXTENSIONS:
        return
    try:
        # Validated on a snapshot first, so an unusable file gets no temporary; the edit then
        # refuses a file that changed since (like tagging)
        source, snapshot = _read_image_snapshot(p, found)
        fmt = get_image_format(source)
        gif = _is_gif(p, fmt)
        if not gif and fmt not in PYEXIV2_FORMATS:
            raise ValueError(f"Unsupported file format: {fmt}" if fmt else "Unreadable image")
        with _image_edit(p, snapshot) as (source, output):
            message = _clear_gif(source, output) if gif else _clear_standard(source, output, fmt)
        separator = ": " if fmt == "GIF" else " for: "
        logger.info(f"{message}{separator}{p.name}")
        print(f"  {message}{separator}{_shown(p.name)}")
    except Exception as e:
        logger.exception(f"Failed to clear {p.name}")
        print(_shown(f"  Failed to clear {p.name}: {e}"))


def _model_image(source: bytes, max_megapixels: float = DEFAULT_MAX_MEGAPIXELS) -> tuple[bytes, str]:
    """
    Prepares the copy of an image that is sent to the model; the file itself is never changed.

    With a pixel budget, the first frame is decoded, turned upright by its EXIF orientation,
    scaled down (never up, aspect ratio kept) to at most max_megapixels and re-encoded without
    metadata: PNG for PNG/GIF sources and anything with transparency (lossless, keeps text
    sharp), JPEG otherwise. With max_megapixels 0 the original bytes are sent unchanged, and
    also when the copy can't be made (e.g. a truncated file Pillow identifies but can't decode).

    Returns:
        The bytes to send and their MIME type.
    """

    if not max_megapixels:
        return _original_image(source)
    try:
        return _scaled_image(source, max_megapixels)
    # Pillow raises errors outside OSError too, e.g. struct.error or zlib.error
    except Exception as error:  # noqa: BLE001 - any failure falls back to the original
        # e.g. a truncated JPEG: verify() doesn't decode JPEG pixels, but servers decode leniently
        logger.warning(f"Could not prepare a scaled copy ({error}); sending the original file instead")
        return _original_image(source)


def _original_image(source: bytes) -> tuple[bytes, str]:
    """The original bytes and their Pillow-detected MIME type (fallback image/jpeg)."""

    return source, MIME_TYPES.get(get_image_format(source) or "", DEFAULT_MIME_TYPE)


def _scaled_image(source: bytes, max_megapixels: float) -> tuple[bytes, str]:
    """The scaled, upright, metadata-free first-frame copy described in _model_image()."""

    budget = max_megapixels * 1_000_000
    with _open_pillow(source) as img:
        lossless = img.format in {"PNG", "GIF"}
        if img.format == "JPEG" and img.width * img.height > budget:
            # Let libjpeg decode at a reduced scale (still at least the target size): much faster for big photos
            scale = math.sqrt(budget / (img.width * img.height))
            img.draft("RGB", (math.ceil(img.width * scale), math.ceil(img.height * scale)))
        frame = ImageOps.exif_transpose(img)  # a copy of the first frame, upright

    if frame.mode in {"I;16", "I;16B", "I;16L"}:
        frame = frame.convert("I").point(lambda value: value / 256).convert("L")  # 16-bit PNG: keep the range
    # "transparency" covers palette images and RGB/grayscale PNGs with a transparent colour (tRNS)
    alpha = frame.mode in {"RGBA", "LA", "PA"} or "transparency" in frame.info
    frame = frame.convert("RGBA" if alpha else "RGB")
    # Pillow carries info through convert()/resize() and its encoders write some of it back
    # (a JPEG comment, a PNG ICC profile): send pixels only
    frame.info = {}
    if frame.width * frame.height > budget:
        scale = math.sqrt(budget / (frame.width * frame.height))
        size = (max(1, int(frame.width * scale)), max(1, int(frame.height * scale)))
        frame = frame.resize(size, Image.Resampling.LANCZOS)

    output = io.BytesIO()
    if lossless or alpha:
        frame.save(output, format="PNG")
        return output.getvalue(), MIME_TYPES["PNG"]
    frame.save(output, format="JPEG", quality=MODEL_JPEG_QUALITY)
    return output.getvalue(), MIME_TYPES["JPEG"]


def get_tags_ollama(
    client: Any,
    model: str,
    img_path: Path,
    prompt: str,
    max_megapixels: float = DEFAULT_MAX_MEGAPIXELS,
    *,
    data: bytes | None = None,
) -> str:
    """
    Sends an image and prompt to an Ollama server for tag generation.

    Args:
        client: The Ollama client instance.
        model: The identifier for the model to use (e.g., 'qwen3-vl:8b').
        img_path: The path to the image file.
        prompt: The prompt instructions for generating tags.
        max_megapixels: Pixel budget for the copy sent (see _model_image(); 0 sends the original).
        data: An already read snapshot of the image (_read_image_snapshot()); read from img_path if None.

    Returns:
        A string containing the generated tags from the model response.
    """

    logger.debug(f"Requesting tags from Ollama ({model}) for {img_path}")
    data, _ = _model_image(_read_image_bytes(img_path) if data is None else data, max_megapixels)
    response = client.chat(
        model=model,
        messages=[{"role": "user", "content": prompt, "images": [data]}],
    )
    content = response.message.content
    logger.debug(f"Raw Ollama response for {img_path}: {_log_excerpt(content)}")
    return content or ""


def get_tags_lm_studio(
    client: Any,
    model: str,
    img_path: Path,
    prompt: str,
    max_megapixels: float = DEFAULT_MAX_MEGAPIXELS,
    *,
    data: bytes | None = None,
) -> str:
    """
    Encodes the image to base64 and sends a request to an LM Studio server.

    Args:
        client: The OpenAI-compatible client instance (e.g., LM Studio).
        model: The model identifier to use.
        img_path: The path to the image file.
        prompt: The text prompt for generating tags.
        max_megapixels: Pixel budget for the copy sent (see _model_image(); 0 sends the original).
        data: An already read snapshot of the image (_read_image_snapshot()); read from img_path if None.

    Returns:
        A string containing the generated tags from the response content.
    """

    logger.debug(f"Requesting tags from LM Studio ({model}) for {img_path}")
    data, mime_type = _model_image(_read_image_bytes(img_path) if data is None else data, max_megapixels)
    base64_image = base64.b64encode(data).decode("utf-8")

    response = client.chat.completions.create(
        model=model,
        messages=[
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": prompt},
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:{mime_type};base64,{base64_image}"},
                    },
                ],
            }
        ],
    )
    # An OpenAI-compatible server may answer with no choices at all
    content = response.choices[0].message.content if response.choices else None
    logger.debug(f"Raw LM Studio response for {img_path}: {_log_excerpt(content)}")
    return content or ""


def _log_excerpt(text: str | None, limit: int = MAX_LOGGED_REPLY_CHARS) -> str | None:
    """A model reply for the log, cut to limit characters: a runaway reply mustn't fill the disk."""
    if text is None or len(text) <= limit:
        return text
    return f"{text[:limit]}... [{len(text) - limit} more characters not logged]"


def _json_list(raw_output: str) -> list | None:
    """The reply as a JSON list: the whole reply, else its first-to-last bracketed segment (None if neither)."""
    candidates = [raw_output]
    start, end = raw_output.find("["), raw_output.rfind("]")
    if start != -1 and end > start:
        candidates.append(raw_output[start : end + 1])
    for candidate in candidates:
        try:
            parsed = json.loads(candidate)
        except (ValueError, RecursionError):
            continue
        if isinstance(parsed, list):
            return parsed
    return None


def parse_model_output(raw_output: str | None) -> list[str] | None:
    """Parse model output and extract tags robustly with normalization.

    Tries multiple patterns (JSON, bullet points, intro text, comma-separated)
    to handle various LLM output styles. Returns None if parsing fails or
    insufficient tags are extracted.

    Args:
        raw_output: The raw string output from the LLM (None when the reply had no content).

    Returns:
        A list of normalized tags, or None if no valid tags could be extracted.
    """

    if not raw_output:
        return None

    # Thinking models (e.g. qwen3, deepseek-r1) may emit <think>...</think> reasoning before the answer.
    # Reasoning that never closed (cut off by max_tokens) has no answer; its prose must not become tags.
    if "</think>" in raw_output:
        raw_output = raw_output.rsplit("</think>", 1)[1]
    elif "<think>" in raw_output:
        return None
    # Markdown code fences around the list ("```" or "```json" lines) are not tags
    raw_output = re.sub(r"^[ \t]*```[\w-]*[ \t]*\r?$", "", raw_output, flags=re.MULTILINE)

    # Pattern 1: JSON array ["tag1", "tag2"] - most reliable. A list with strings is the model's answer, even
    # with too few tags: splitting its text on commas would turn '[true' or 'd]' into tags. A list without
    # strings (e.g. an incidental [1] in prose) falls through to the text patterns.
    parsed = _json_list(raw_output)
    if parsed is not None:
        # bool is an int subclass, but true/false are not tags
        json_tags = [
            str(x).strip().lower() for x in parsed if isinstance(x, (str, int, float)) and not isinstance(x, bool)
        ]
        normalized = normalize_tags(json_tags)
        if normalized or any(isinstance(x, str) for x in parsed):
            return normalized

    # Pattern 2: Bullet points at line start (minimum 6 items expected); hyphens inside tags are not bullets.
    # A Markdown "*" bullet needs a space after it, so a bold "**Tags:**" line is not one.
    bullets = re.findall(r"^[ \t]*(?:[-•★●]|\*(?=[ \t]))[ \t]*(\S.*)", raw_output, re.MULTILINE)
    if len(bullets) >= 6:
        return normalize_tags([t.strip().strip("\"'").lower() for b in bullets for t in b.split(",")])

    # Pattern 3: Numbered lists like "1. tag" (minimum 6 items expected)
    numbered = re.findall(r"(?<!\d)\d+\.\s+(.+)", raw_output)
    if len(numbered) >= 6:
        return normalize_tags([t.strip().strip("\"'").lower() for n in numbered for t in n.split(",")])

    # Pattern 4: "Here are the tags:" style intro text extraction. Needs a colon later on the same line
    # ("tags for this image:") or a dash right after, so a list item like "text tags" doesn't count.
    text_after_intro = re.match(
        r".{0,40}?\b(?:tags|keywords)\b(?:[^:\n]{0,40}:|\s*-)\s*(.+)",
        raw_output,
        re.IGNORECASE | re.DOTALL,
    )
    if text_after_intro:
        return normalize_tags(parse_text_tags(text_after_intro.group(1)))

    # Fallback: comma- and/or newline-separated
    return normalize_tags([tag.strip().strip("\"'").lower() for tag in re.split(r"[,\n]", raw_output) if tag.strip()])


def parse_text_tags(text: str) -> list[str]:
    """Parse tags from text that follows intro patterns.

    Args:
        text: The raw text output from the model.

    Returns:
        A list of extracted and cleaned tag strings.
    """

    # Split by commas or newlines
    parts = re.split(r"[,\n]+", text)
    tags = []
    for part in parts:
        part = part.strip().strip("\"'").lower()
        # Skip common non-tag words (short real tags like '3d' or 'ui' are kept)
        if part and part not in ["and", "or", "the", "a", "an", "is", "are", "of"]:
            tags.append(part)
    return tags


def normalize_tags(tags: list[str], min_count: int = 6, max_count: int = 12) -> list[str] | None:
    """Normalize tags and enforce count constraints.

    Normalizes each tag (lowercase, strip whitespace), drops tags longer than
    MAX_TAG_LENGTH, removes duplicates while preserving order, then enforces the
    6-12 tag minimum from your prompt.
    Returns None if fewer than min_count valid tags remain.

    Args:
        tags: A list of raw tags extracted from the model output.
        min_count: The minimum number of tags required to be considered valid.
        max_count: The maximum number of tags to keep.

    Returns:
        A list of normalized tags, or None if the count is below min_count.
    """

    # Strip, lowercase, drop sentence-length entries, remove duplicates while preserving order
    seen = set()
    normalized = []
    for tag in tags:
        tag = tag.strip().lower()
        if tag and len(tag) <= MAX_TAG_LENGTH and tag not in seen:
            seen.add(tag)
            normalized.append(tag)

    # Enforce max_count (12) by trimming excess
    if len(normalized) > max_count:
        return normalized[:max_count]

    # Return None if we don't meet minimum, let caller decide how to handle it
    return normalized if len(normalized) >= min_count else None


def _contains_marker(value: object) -> bool:
    """Returns True if a metadata value (str, bytes or other) contains the processed marker."""

    if isinstance(value, bytes):
        value = value.decode("utf-8", errors="ignore")
    return bool(value) and PROCESSED_MARKER in str(value)


def _pyexiv2_has_marker(p: Path, data: bytes | None = None) -> bool:
    """
    Checks every EXIF and XMP value for the processed marker.

    Raises:
        Exception: If pyexiv2 cannot open the file.
    """

    values = []
    # Hand pyexiv2 the bytes, not the path: on Windows it can't open non-ASCII paths like 'ö'
    if data is None:
        data = _read_image_bytes(p)
    with metadata_lock, pyexiv2.ImageData(data) as img:
        # Read EXIF and XMP independently so one failing doesn't kill both
        for kind, read in (("EXIF", img.read_exif), ("XMP", img.read_xmp)):
            try:
                values.extend(read().values())
            except Exception as e:  # noqa: BLE001 - the other read may still find the marker
                _warn(f"Could not read the {kind} metadata of {p.name} ({e})")
    return any(_contains_marker(v) for v in values)


def _pillow_has_marker(p: Path, data: bytes | None = None) -> bool:
    """
    Checks Pillow's text metadata (e.g. PNG text chunks) for the processed marker.

    Raises:
        Exception: If Pillow cannot open the file.
    """

    with _open_pillow(p if data is None else data) as img:
        return any(isinstance(v, str) and PROCESSED_MARKER in v for v in img.info.values())


def is_already_processed(img_path: Path, fmt: str | None = None, data: bytes | None = None) -> bool:
    """Checks if the image already contains the AI processed marker.

    Like tag_image(), it goes by the real format, not the extension: a PNG named
    .gif is tagged via pyexiv2, so its marker is in EXIF/XMP, not a GIF comment.

    Args:
        img_path: The path to the image file to check.
        fmt: The format from get_image_format(); looked up if None.
        data: An already read snapshot of the image; read from img_path if None.

    Returns:
        True if the marker is found in metadata or comments, False otherwise.
    """

    p = Path(img_path)
    if p.suffix.lower() not in IMAGE_EXTENSIONS:
        return False

    source = p if data is None else data
    if _is_gif(p, fmt or get_image_format(source)):
        try:
            with _open_pillow(source) as img:
                return _contains_marker(img.info.get("comment"))
        except Exception as e:  # noqa: BLE001
            _warn(f"Could not read the GIF comment of {p.name} ({e}); treating it as not yet tagged")
        return False

    # 1. Primary metadata inspection using pyexiv2
    try:
        if _pyexiv2_has_marker(p, data):
            return True
    except Exception as e:  # noqa: BLE001 - unreadable metadata means "not processed"
        _warn(f"pyexiv2 could not read the metadata of {p.name} ({e}); checking it with Pillow instead")

    # 2. Fully isolated fallback check using Pillow
    try:
        return _pillow_has_marker(p, data)
    except Exception as e:  # noqa: BLE001
        _warn(f"Could not read the metadata of {p.name} ({e}); treating it as not yet tagged")
    return False


def process_single_image(
    img_path: Path,
    client: Any,
    backend: str,
    model: str,
    prompt: str,
    stop_event: threading.Event,
    max_megapixels: float = DEFAULT_MAX_MEGAPIXELS,
    found: os.stat_result | None = None,
) -> tuple[str, str, str, float]:
    """Handles the full pipeline for a single image: validation -> AI -> tagging.

    Args:
        img_path: The path to the image file to process.
        client: The client instance for the chosen backend (Ollama or OpenAI).
        backend: The backend type ('ollama' or 'lm-studio').
        model: The model identifier to use.
        prompt: The prompt instructions for tag generation.
        stop_event: A threading.Event to monitor for user cancellation.
        max_megapixels: Pixel budget for the copy sent to the model (0 sends the original).
        found: The file's lstat from _find_images(); a different file at the path is refused.

    Returns:
        A tuple containing (status, filename, message, duration).
    """

    logger.info(f"Processing {img_path.name}")
    # One guarded read serves the format and skip checks and the model; tag_image() then refuses
    # a file that no longer matches it (replaced or modified while the model was working)
    try:
        data, snapshot = _read_image_snapshot(img_path, found)
    except OSError as e:  # e.g. a folder writable by others, a symlinked folder or no read permission
        logger.warning(f"Failed: could not read {img_path.name}: {e}")
        return "FAILED", img_path.name, f"Could not read image: {e}", 0
    fmt = get_image_format(data)
    if fmt is None:
        logger.warning(f"Failed: unreadable image {img_path.name}")
        return "FAILED", img_path.name, "Unreadable image (unsupported or corrupted file)", 0
    if fmt not in TAGGABLE_FORMATS:
        # e.g. a BMP named .jpg or an MPO (multi-picture) JPEG: fail before asking the model
        logger.warning(f"Failed: {img_path.name} has unsupported format {fmt}")
        return "FAILED", img_path.name, f"Unsupported file format: {fmt}", 0

    # Skip check
    if is_already_processed(img_path, fmt, data):
        logger.info(f"Skipping already processed image: {img_path.name}")
        return "SKIPPED", img_path.name, "Skipped: Already Tagged", 0

    if stop_event.is_set():
        logger.info(f"Cancelled before start: {img_path.name}")
        return "CANCELLED", img_path.name, "Cancelled by user", 0

    start = time.monotonic()  # Start timing the actual processing
    try:
        get_tags = get_tags_ollama if backend == "ollama" else get_tags_lm_studio
        raw_output = get_tags(client, model, img_path, prompt, max_megapixels, data=data)

        # Parse model output robustly (handles JSON, bullets, intro text, or comma-separated)
        parsed_tags = parse_model_output(raw_output)

        if not parsed_tags:
            logger.warning(
                f"Failed to extract valid tags from model response for {img_path.name} after {time.monotonic() - start:.1f}s"
            )
            return (
                "FAILED",
                img_path.name,
                "Invalid or insufficient tags returned from model",
                time.monotonic() - start,
            )

        tag_image(str(img_path), parsed_tags, fmt=fmt, expected=snapshot)
        logger.info(f"Tagged {img_path.name} in {time.monotonic() - start:.1f}s with {parsed_tags}")
        return (
            "SUCCESS",
            img_path.name,
            f"Generated Tags: {parsed_tags}",
            time.monotonic() - start,
        )

    except Exception as e:
        logger.exception(f"Error processing {img_path.name} after {time.monotonic() - start:.1f}s")
        return "FAILED", img_path.name, str(e), time.monotonic() - start


@dataclass
class _RunStats:
    """Running totals for one process_directory() call."""

    success: int = 0
    skipped: int = 0
    failed: int = 0
    success_duration: float = 0.0
    failed_log: list[tuple[str, str]] = field(default_factory=list)

    def record(self, status: str, name: str, message: str, duration: float) -> None:
        """Prints one process_single_image() result and adds it to the totals."""

        name, message = _shown(name), _shown(message)
        if status == "SUCCESS":
            tqdm.write(f"  [✓] {name} -> {message}")
            self.success += 1
            self.success_duration += duration
        elif status == "SKIPPED":
            tqdm.write(f"  [-] {name} -> {message}")
            self.skipped += 1
        elif status == "CANCELLED":
            # Do nothing for cancelled tasks to keep the console clean
            pass
        else:  # FAILED
            tqdm.write(f"  [!] {name} -> {message}")
            self.failed += 1
            self.failed_log.append((name, message))


def _without_leading_parent_refs(path: Path) -> Path:
    """
    Resolves leading '..' parts ('../memes') against the working directory, which os.getcwd()
    returns without links on POSIX (and Windows resolves '..' by name anyway), so this names the
    same folder the shell meant. A '..' after another part could follow a link back out of it, so
    _image_parent() still refuses that.
    """
    parts = path.parts
    count = 0
    while count < len(parts) and parts[count] == "..":
        count += 1
    if not count:
        return path
    base = Path(os.getcwd())
    for _ in range(count):
        base = base.parent
    return base.joinpath(*parts[count:])


def _find_images(directory: str, recursive: bool) -> dict[Path, os.stat_result]:
    """
    Finds the regular files in directory (optionally recursive) with a supported image extension,
    each with its lstat: readers refuse a different file at that path later (see _source_bytes()).
    """

    base_path = _without_leading_parent_refs(Path(directory))
    with _image_parent(base_path / ".image-directory-check"):
        # Opening it is enough to know it can be listed: rglob() silently finds nothing in a folder it can't list
        try:
            os.scandir(base_path).close()
        except OSError as error:
            raise OSError(error.errno, f"Could not list the image folder: {error.strerror}", directory) from error
        files = base_path.rglob("*") if recursive else base_path.iterdir()
        # Reads revalidate ancestors and the opened leaf; this filter only avoids existing links.
        found = {}
        for file in files:
            if (
                file.suffix.lower() in IMAGE_EXTENSIONS
                and (info := _lstat_or_none(file))
                and stat.S_ISREG(info.st_mode)
            ):
                found[file] = info
        return found


def _lstat_or_none(path: Path) -> os.stat_result | None:
    """The path's own lstat (a link is not followed), or None if it vanished or can't be examined."""
    try:
        return path.lstat()
    except OSError:
        return None


def _load_prompt() -> str:
    """
    Loads prompt.txt from the script directory, falling back to DEFAULT_PROMPT
    if it doesn't exist. Exits the program if it exists but cannot be read.
    """

    prompt_file = Path(__file__).parent / "prompt.txt"
    if not prompt_file.exists():
        logger.warning(f"prompt.txt not found at {prompt_file}; using default")
        print(f"Warning: Could not read prompt.txt from {prompt_file}. Falling back to default.")
        return DEFAULT_PROMPT

    try:
        prompt = prompt_file.read_text(encoding="utf-8").strip()
    except Exception as e:
        logger.exception("Failed to read prompt.txt")
        print(f"Error: Could not read prompt.txt from {prompt_file}: {e}")
        sys.exit(1)
    if not prompt:
        logger.error(f"prompt.txt at {prompt_file} is empty")
        print(f"Error: prompt.txt at {prompt_file} is empty. Write a prompt into it or delete it to use the default.")
        sys.exit(1)
    logger.info(f"Using prompt from {prompt_file}")
    return prompt


def _create_client(backend: str, host: str, timeout: float = DEFAULT_TIMEOUT) -> Any:
    """
    Builds the model client for the chosen backend.

    Args:
        backend: The backend type ('ollama' or 'lm-studio').
        host: The endpoint URL for the chosen backend.
        timeout: Seconds to wait for a model reply before the request fails.

    Returns:
        The ollama Client or the LM Studio OpenAI client.
    """

    # Both SDKs follow redirects by default, which would let the selected server send the request
    # (image and prompt) on to any other host this machine can reach.
    if backend == "ollama":
        # The ollama client adds OLLAMA_API_KEY (meant for ollama.com) to every host; strip it per request
        return OllamaClient(host=host, timeout=timeout, follow_redirects=False, auth=_without_authorization)
    # No retries: a timed-out request would be resent to a server still busy with it. Omit() drops the
    # OpenAI-Organization/-Project headers the SDK would otherwise fill in from OPENAI_ORG_ID/OPENAI_PROJECT_ID.
    return OpenAI(
        base_url=f"{host.rstrip('/')}/v1",
        api_key="lm-studio",
        timeout=timeout,
        max_retries=0,
        default_headers={"OpenAI-Organization": Omit(), "OpenAI-Project": Omit()},
        http_client=DefaultHttpxClient(follow_redirects=False),
    )


def _without_authorization(request: Any) -> Any:
    """httpx auth hook for the ollama client: send no Authorization header to the model server."""

    request.headers.pop("authorization", None)
    return request


class _ServerCheckError(Exception):
    """The model server can't be reached or doesn't offer the requested model."""


def _available_models(client: Any, backend: str) -> list[str]:
    """Returns the model names the server offers (Ollama /api/tags, LM Studio /v1/models)."""

    if backend == "ollama":
        return [m.model for m in client.list().models if m.model]
    return [m.id for m in client.models.list() if m.id]


def _model_matches(name: str, model: str, backend: str) -> bool:
    """Tells whether the listed model name is the model the user asked for."""

    if name == model:
        return True
    if backend == "ollama":  # Ollama adds the default tag: "llava" means "llava:latest"
        return ":" not in model.rsplit("/", 1)[-1] and name == f"{model}:latest"
    return name.startswith(f"{model}@")  # LM Studio lists extra quantizations as "<id>@<quant>"


def _check_server(backend: str, host: str, model: str, timeout: float = DEFAULT_TIMEOUT) -> None:
    """
    Fails fast if the server is down or lacks the model, instead of failing every image separately.

    Raises:
        _ServerCheckError: The server could not be reached or does not list the model.
    """

    label = "Ollama" if backend == "ollama" else "LM Studio"
    try:
        with contextlib.closing(_create_client(backend, host, min(timeout, SERVER_CHECK_TIMEOUT))) as client:
            models = _available_models(client, backend)
    except Exception as e:  # connection refused, timeout, HTTP error or an unexpected reply
        logger.exception(f"Server check failed for {host}")
        raise _ServerCheckError(f"Could not reach the {label} server at {host}: {e}") from e

    if any(_model_matches(name, model, backend) for name in models):
        logger.info(f"Server check passed: {host} offers {model}")
        return
    available = ", ".join(sorted(set(models))) or "none"
    if backend == "ollama":
        hint = f"Download it with: ollama pull {model}"
    else:
        hint = "LM Studio model ids differ from Ollama names (e.g. qwen/qwen3-vl-8b); pass one with --model"
    logger.error(f"Model {model} not offered by {host}; available: {available}")
    raise _ServerCheckError(
        f"The {label} server at {host} has no model '{model}'. Available models: {available}. {hint}."
    )


def _run_tasks(
    image_files: dict[Path, os.stat_result | None],
    client: Any,
    backend: str,
    model: str,
    prompt: str,
    max_workers: int,
    stop_event: threading.Event,
    max_megapixels: float = DEFAULT_MAX_MEGAPIXELS,
) -> _RunStats:
    """Tags image_files (path -> lstat from _find_images()) concurrently with a progress bar; returns the totals."""

    stats = _RunStats()
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_image = {
            executor.submit(
                process_single_image,
                img_path,
                client,
                backend,
                model,
                prompt,
                stop_event,
                max_megapixels,
                found,
            ): img_path
            for img_path, found in image_files.items()
        }

        stopped_notified = False
        for future in tqdm(
            as_completed(future_to_image),
            total=len(image_files),
            desc="Processing images",
        ):
            if stop_event.is_set() and not stopped_notified:
                tqdm.write("  [!] Stop signal received (Q pressed). Finishing currently running tasks...")
                logger.info("Stop requested (Q); finishing in-flight images, cancelling queued ones")
                stopped_notified = True

            try:
                stats.record(*future.result())
            except Exception as e:  # one bad image must not abort the batch
                img_path = future_to_image[future]
                logger.exception(f"Unexpected error for {img_path}")
                tqdm.write(_shown(f"  [!] {img_path} -> Unexpected Error: {e}"))
                stats.failed += 1
                stats.failed_log.append((_shown(img_path.name), _shown(f"Unexpected Error: {e}")))

    return stats


def _print_report(stats: _RunStats, total_seconds: float) -> None:
    """Prints the end-of-run summary."""

    hours, remainder = divmod(total_seconds, 3600)
    minutes, seconds = divmod(remainder, 60)

    print("\n" + "=" * 50)
    print("                PROCESSING REPORT")
    print("=" * 50)
    print(f" Processed images: {stats.success}")
    print(f" Skipped images: {stats.skipped}")
    print(f" Failed images: {stats.failed}")
    print(f" Total time elapsed: {int(hours)}h {int(minutes)}m {seconds:.2f}s")

    if stats.success > 0:
        avg_latency = stats.success_duration / stats.success
        print(f" Average processing time: {avg_latency:.2f} seconds")

    if stats.failed_log:
        print("\n--- Failed files details ---")
        for filename, error_msg in stats.failed_log:
            print(f" * {filename} -> {error_msg}")

    print("=" * 50)


def clear_directory(
    directory: str,
    recursive: bool = False,
    max_workers: int = 1,
) -> None:
    """
    Clears metadata (EXIF, XMP, IPTC) and comments from all supported images in a directory.

    Args:
        directory: The root directory to scan for images.
        recursive: Whether to include subdirectories.
        max_workers: Number of concurrent worker threads (1 to 4).
    """

    base_path = Path(directory)
    if not base_path.is_dir():
        print(f"Error: The path '{directory}' is not a valid directory.")
        return

    image_files = _find_images(directory, recursive)
    if not image_files:
        print(f"No valid images found in '{directory}'.")
        return

    print(f"Resetting tags for {len(image_files)} images...")
    logger.info(
        f"Clearing tags from {len(image_files)} images in {directory} (recursive={recursive}, workers={max_workers})"
    )
    if max_workers > 1:
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            list(executor.map(clear_tags, image_files, image_files.values()))
    else:
        for img_path, found in image_files.items():
            clear_tags(img_path, found)
    print("Done.")
    logger.info("Clearing finished")


def process_directory(
    directory: str,
    recursive: bool = False,
    backend: str = "ollama",
    host: str | None = None,
    model: str = DEFAULT_MODEL,
    max_workers: int = 1,
    clear: bool = False,
    timeout: float = DEFAULT_TIMEOUT,
    max_megapixels: float = DEFAULT_MAX_MEGAPIXELS,
) -> None:
    """
    Orchestrates the image tagging process (or clearing when clear=True) for a directory.

    This function handles prompt loading, backend initialization (Ollama or LM Studio),
    concurrent task distribution via ThreadPoolExecutor, and provides a real-time progress
    bar and final summary report. When clear=True, it delegates to clear_directory().

    Args:
        directory: The root directory to scan for images.
        recursive: Whether to include subdirectories in the search.
        backend: The model provider backend ('ollama' or 'lm-studio').
        host: The endpoint URL for the chosen backend; defaults to its localhost URL (DEFAULT_HOSTS).
        model: The specific model name/ID to use.
        max_workers: The maximum number of concurrent threads (the CLI allows 1-4).
        clear: If True, clears metadata and comments instead of tagging.
        timeout: Seconds to wait for each model reply before that image fails.
        max_megapixels: Pixel budget for the copy of each image sent to the model (0 sends the original).

    Raises:
        _ServerCheckError: When tagging, the server could not be reached or does not list the model.
    """

    if clear:
        clear_directory(directory, recursive, max_workers)
        return

    image_files = _find_images(directory, recursive)
    if not image_files:
        print(f"No valid images found in '{directory}'.")
        return

    host = host or DEFAULT_HOSTS[backend]
    print(f"Initialized backend: {backend} | Target: {host}")
    print(f"Found {len(image_files)} images to process. Starting...\n")
    logger.info(
        f"Tagging {len(image_files)} images in {directory} (recursive={recursive}) via {backend} at {host}: "
        f"model={model}, workers={max_workers}, timeout={timeout:g}s, max_pixels={max_megapixels:g} MP"
    )

    prompt = _load_prompt()
    logger.debug(f"Prompt: {prompt}")
    _check_server(backend, host, model, timeout)
    client = _create_client(backend, host, timeout)

    start_time = time.monotonic()

    # Concurrency and quitting
    stop_event = threading.Event()
    quit_thread = threading.Thread(target=listen_for_quit, args=(stop_event,), daemon=True)
    quit_thread.start()

    try:
        print(f"Starting concurrent processing (max_workers={max_workers}).")
        print("Press 'q' at any time to stop and see the current report.\n")
        stats = _run_tasks(image_files, client, backend, model, prompt, max_workers, stop_event, max_megapixels)
    except Exception as e:
        print(f"An unexpected error occurred during processing: {e}")
        raise
    finally:
        # Also stops the quit listener after a normal finish, so it restores the
        # terminal (POSIX) and the report isn't held up waiting for it.
        stop_event.set()
        quit_thread.join(timeout=2)
        client.close()

    total_seconds = time.monotonic() - start_time
    _print_report(stats, total_seconds)
    logger.info(
        f"Finished in {total_seconds:.1f}s: {stats.success} tagged, {stats.skipped} skipped, {stats.failed} failed"
    )


def _build_parser() -> argparse.ArgumentParser:
    """Builds the command-line parser."""

    parser = argparse.ArgumentParser(description="Image tagger using a vision-language model")
    parser.add_argument("directory", help="Path to your image folder")
    parser.add_argument(
        "-r",
        "--recursive",
        action="store_true",
        help="process subdirectories recursively",
    )
    parser.add_argument(
        "--backend",
        choices=["ollama", "lm-studio"],
        default="ollama",
        help="local model provider backend (ollama by default)",
    )
    parser.add_argument("--host", help="backend endpoint URL (localhost by default)")
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help=f"model identification tag (defaults to {DEFAULT_MODEL})",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=1,
        help="number of concurrent workers (max 4, default 1)",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=DEFAULT_TIMEOUT,
        help=f"seconds to wait for each model reply before the image fails (default {DEFAULT_TIMEOUT:g})",
    )
    parser.add_argument(
        "--max-pixels",
        type=float,
        default=DEFAULT_MAX_MEGAPIXELS,
        metavar="MEGAPIXELS",
        help=(
            "scale the copy sent to the model down to at most this many megapixels "
            f"(default {DEFAULT_MAX_MEGAPIXELS:g}; 0 sends the original file); the files are not changed"
        ),
    )
    parser.add_argument("--log", help="enable logging and append to this .log file (e.g., --log logs/run.log)")
    parser.add_argument(
        "--clear",
        action="store_true",
        help="clear metadata (EXIF/XMP/IPTC) and comments from images instead of tagging",
    )
    return parser


def _argument_error(args: argparse.Namespace) -> str | None:
    """Returns the message for the first invalid argument, or None if they are all valid."""

    if not Path(args.directory).is_dir():
        return f"The folder '{args.directory}' could not be located."
    # Max 4 workers as it's the default limit for both ollama and LM Studio.
    if not 1 <= args.workers <= 4:
        return f"Workers must be between 1 and 4, got {args.workers}"
    # isfinite also rejects nan (nan <= 0 is false) and inf (the HTTP clients' sockets overflow on it)
    if not math.isfinite(args.timeout) or args.timeout <= 0:
        return f"Timeout must be a positive number of seconds, got {args.timeout:g}"
    if not math.isfinite(args.max_pixels) or args.max_pixels < 0:
        return f"Max pixels must be zero or a positive number of megapixels, got {args.max_pixels:g}"
    return None


def main(argv: list[str] | None = None) -> int:
    """
    Runs the command-line interface.

    Args:
        argv: The arguments without the program name; defaults to sys.argv[1:].

    Returns:
        The exit code: 0, or 1 for invalid arguments, an unopenable log, an unsafe or unreadable
        image folder or an unreachable server (or one without the model).
    """

    args = _build_parser().parse_args(argv)

    # Redirected output on Windows uses the ANSI code page (e.g. cp1252), which can't encode
    # "✓" or many file names; print "?" for those instead of failing the image or the run.
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(errors="replace")

    if log_error := _log_path_error(args.log):
        print(f"Error: {log_error}.")
        return 1

    # Before the log is opened, so an invalid run creates no log file or folders
    if error := _argument_error(args):
        print(f"Error: {error}")
        return 1

    try:
        setup_logging(args.log)
    except OSError as e:
        print(f"Error: Could not open the log file '{args.log}': {e}")
        return 1

    try:
        process_directory(
            args.directory,
            args.recursive,
            args.backend,
            args.host,
            args.model,
            args.workers,
            clear=args.clear,
            timeout=args.timeout,
            max_megapixels=args.max_pixels,
        )
    # The folder itself, e.g. _UnsafeImagePath or no permission to list it (per-image problems are reported per image)
    except OSError as e:
        logger.exception("Refused the image folder")
        print(f"Error: {_shown(str(e))}")
        return 1
    except _ServerCheckError as e:  # already logged by _check_server(); the model names come from the server
        print(f"Error: {_shown(str(e))}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
